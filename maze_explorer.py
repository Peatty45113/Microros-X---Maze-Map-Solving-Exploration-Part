# ▸ norm_angle(a): รับมุมเรเดียนค่าใดก็ได้ คืนมุมทิศเดียวกันในช่วง -pi ถึง +pi
#   ใช้ตอนลบมุมสองมุม เช่น 179° - (-179°) จะได้ -2° (ทางสั้น) ไม่ใช่ 358°
def norm_angle(a):                               # บีบมุม a (เรเดียน) ให้อยู่ในช่วง -pi ถึง +pi
    # ▸ sin กับ cos ไม่สนว่ามุมวนมากี่รอบ แล้ว atan2 แปลงกลับเป็นมุมในช่วง [-pi, pi] เสมอ
    return math.atan2(math.sin(a), math.cos(a))  # sin/cos แล้ว atan2 กลับ = มุมเดิมในช่วง [-pi, pi]


# ▸ clamp(v, lo, hi): จำกัดค่า v ไม่ให้ต่ำกว่า lo และไม่เกิน hi เช่น clamp(1.5, -0.4, 0.4) = 0.4
def clamp(v, lo, hi):                            # จำกัดค่า v ให้อยู่ระหว่าง lo กับ hi
    # ▸ min(hi, v) ตัดส่วนที่เกิน hi ออก แล้ว max(lo, ...) ตัดส่วนที่ต่ำกว่า lo ออก
    return max(lo, min(hi, v))                   # ตัดส่วนที่เกิน hi และต่ำกว่า lo ทิ้ง



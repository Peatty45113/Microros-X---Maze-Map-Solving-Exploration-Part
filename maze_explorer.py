# ▸ main(): ฟังก์ชันแรกที่ทำงาน: เริ่ม ROS 2 -> สร้างโหนด -> ทำงานจนกด Ctrl+C -> หยุด + บันทึกแผนที่
def main():                                       # ฟังก์ชันแรกที่ทำงาน
    # ▸ ลองเริ่ม ROS 2 แบบที่เราจัดการ Ctrl+C เอง
    try:                                          # เริ่ม ROS 2 แบบจัดการ Ctrl+C เอง
        # ▸ นำเข้าตัวเลือกจัดการสัญญาณ (มีใน ROS 2 รุ่นใหม่)
        from rclpy.signals import SignalHandlerOptions             # ตัวเลือกจัดการสัญญาณ (ROS 2 รุ่นใหม่)
        # ▸ ไม่ให้ ROS ปิดตัวเองตอนกด Ctrl+C เราจะได้ยังส่งคำสั่งหยุดและบันทึกแผนที่ได้
        rclpy.init(signal_handler_options=SignalHandlerOptions.NO) # Ctrl+C แล้วยังส่งคำสั่งหยุดและบันทึกแผนที่ได้
    # ▸ ถ้าเป็น ROS 2 รุ่นเก่า (เช่น Foxy) ที่ไม่มีตัวเลือกนี้
    except (ImportError, TypeError):              # ROS 2 รุ่นเก่า
        # ▸ เริ่ม ROS 2 แบบปกติ
        rclpy.init()                              # ... เริ่มแบบปกติ

    # ▸ สร้างโหนด (เรียก __init__ ข้างบน: ประกาศพารามิเตอร์ สร้าง publisher/subscriber/timer)
    node = MazeExplorer()                         # สร้างโหนด
    # ▸ ส่วนทำงานหลัก
    try:                                          # ทำงานหลัก
        # ▸ ให้โหนดทำงานไปเรื่อย ๆ (เรียก callback และ loop() ตาม timer) จนกด Ctrl+C
        rclpy.spin(node)                          # วนทำงานจนกด Ctrl+C
    # ▸ ถ้ากด Ctrl+C
    except KeyboardInterrupt:                     # กด Ctrl+C
        # ▸ พิมพ์บอกว่าถึงเส้นชัยแล้ว กำลังหยุดหุ่นยนต์
        print('\nCtrl+C -> goal reached, stopping robot.')   # ... ถึงเส้นชัย
    # ▸ ถ้าเกิด error อื่น
    except Exception as e:  # noqa: BLE001        # error อื่น
        # ▸ พิมพ์ข้อความ error
        print(f'\nStopped: {e}')                  # ... พิมพ์ error
    # ▸ finally: ทำเสมอ ไม่ว่าจะจบแบบไหน
    finally:                                      # ทำเสมอ
        # ▸ ลองหยุดหุ่นยนต์
        try:                                      # ลองหยุดหุ่นยนต์
            # ▸ 1) ส่งความเร็ว 0 ห้าครั้ง
            node.stop_robot()                     # ... 1) หยุด
        # ▸ ถ้าหยุดไม่ได้ (เช่น ROS ปิดไปแล้ว)
        except Exception:  # noqa: BLE001         # หยุดไม่ได้
            # ▸ ข้ามไป ไม่ต้องทำอะไร
            pass                                  # ... ข้าม
        # ▸ 2) บันทึกแผนที่และบันทึกเส้นทาง
        node.save_map()                           # 2) บันทึกแผนที่
        # ▸ 3) ปิดโหนด คืนทรัพยากร
        node.destroy_node()                       # 3) ปิดโหนด
        # ▸ ถ้า ROS 2 ยังเปิดอยู่
        if rclpy.ok():                            # ROS 2 ยังเปิดอยู่
            # ▸ ปิด ROS 2
            rclpy.shutdown()                      # ... ปิด



# ▸ สร้างคลาส MazeExplorer ที่สืบทอดจาก Node จึงมีความสามารถของโหนด ROS 2 ทั้งหมด
#   (สร้าง publisher, subscriber, timer, logger ได้)
class MazeExplorer(Node):                    # โหนด ROS 2 (สืบทอดจาก Node)

    # ▸ __init__ คือ constructor: ทำงานครั้งเดียวตอนสร้างโหนด (ตอนเริ่มโปรแกรม)
    def __init__(self):                      # ทำงานครั้งเดียวตอนเริ่มโปรแกรม
        # ▸ เรียก constructor ของ Node และตั้งชื่อโหนด จะเห็นชื่อนี้ใน "ros2 node list"
        super().__init__('maze_explorer')    # ตั้งชื่อโหนดว่า maze_explorer

        # ------------------------------------------------------------------
        # 1) พารามิเตอร์ (เปลี่ยนตอนรันได้ด้วย --ros-args -p ชื่อ:=ค่า)
        # ------------------------------------------------------------------
        # ▸ ตั้งชื่อเล่น p ให้ self.declare_parameter จะได้พิมพ์สั้นลง: p('ชื่อ', ค่าเริ่มต้น)
        p = self.declare_parameter   # ชื่อสั้นของฟังก์ชันประกาศพารามิเตอร์

        # ▸ ชื่อ topic ที่ LiDAR ส่งข้อมูลมา (ค่าเริ่มต้น /scan เหมือนในสไลด์ 8)
        p('scan_topic', '/scan')          # topic LiDAR (input)
        # ▸ ชื่อ topic ที่เราส่งคำสั่งความเร็วไปให้ล้อ (เหมือน test_cmd_vel.py)
        p('cmd_vel_topic', '/cmd_vel')    # topic คำสั่งความเร็ว (output)
        # ▸ ชื่อ topic ตำแหน่งหุ่นยนต์จาก encoder/IMU
        p('odom_topic', '/odom')          # topic odometry (input)
        # ▸ loop() ทำงานกี่ครั้งต่อวินาที: 20 Hz = ทุก 0.05 วินาที
        p('control_rate', 20.0)           # loop() ทำงาน 20 ครั้งต่อวินาที

        # ▸ ความกว้างทางเดิน (= ขนาด 1 ช่อง) ถ้าเป็น 0 โปรแกรมจะวัดจาก LiDAR เองตอนเริ่ม
        p('cell_size', 0.0)           # ความกว้างทางเดิน/ขนาดช่อง [m]: 0.30 หรือ 0.40; 0 = วัดเองตอนเริ่ม
        # ▸ ความเร็วเดินหน้า 0.08 m/s (ช้าพอให้ Gmapping ทำแผนที่ได้แม่น ตามสไลด์ 8)
        p('linear_speed', 0.08)       # ความเร็วเดินหน้า [m/s] (สไลด์ 8 แนะนำราว 0.1)
        # ▸ ความเร็วหมุนสูงสุด 0.5 rad/s (ประมาณ 29 องศาต่อวินาที)
        p('turn_speed', 0.5)          # ความเร็วหมุนสูงสุด [rad/s] (สไลด์ 8 แนะนำราว 0.5)
        # ▸ ค่า Kp ของตัวควบคุมระยะ: ห่างจากกลางทาง 1 cm -> หมุนแก้ 0.025 rad/s
        p('kp', 2.5)                  # ค่า P คุมระยะกลางทางเดิน
        # ▸ ★ ค่า P ของตัวควบคุมมุม: เอียง 1 rad -> หมุนแก้ 1.5 rad/s (เอียง 2° -> ~0.05 rad/s)
        p('heading_kp', 1.5)          # ★ ค่า P คุมมุม (ให้ขนานกำแพง)
        # ▸ ขณะเดินหน้า ห้ามหมุนแก้เกิน 0.4 rad/s (กันการส่ายแรง)
        p('max_correction', 0.4)      # ขณะเดิน หมุนแก้ได้มากสุด [rad/s]
        # ▸ ★ แรงดึงเข้ากลางทางสูงสุด 0.10 rad/s: น้อยกว่าแรงคุมมุม หุ่นยนต์จึงไหลเข้ากลางทางช้า ๆ โดยตัวยังขนานกำแพง
        p('max_push', 0.10)           # ★ แรงดึงเข้ากลางทางสูงสุด [rad/s] (น้อยกว่าแรงคุมมุม -> ตัวยังขนานกำแพง)
        # ▸ ★ กำแพงข้างตัวต้องใกล้กว่า 0.75 เท่าของความกว้างทาง (30 cm -> 22.5 cm) จึงนับว่าเป็นกำแพงทางเดิน
        p('wall_near_ratio', 0.75)    # ★ กำแพงข้างตัวต้องใกล้กว่า 0.75 x ความกว้างทาง จึงใช้คุมกลางทาง
        # ▸ หยุดเมื่อกำแพงหน้าห่าง ครึ่งช่อง + 2 cm (30 cm -> หยุดที่ 17 cm = ตัวอยู่กลางช่องพอดี)
        p('front_gap', 0.02)          # หยุดเมื่อกำแพงหน้าอยู่ห่าง (ครึ่งช่อง + ค่านี้) [m]
        # ▸ ต้องเห็นทางเปิดด้านข้างติดกัน 3 รอบ (0.15 วินาที) ถึงเชื่อว่าเป็นทางแยกจริง
        p('open_confirm_ticks', 3)    # ต้องเห็นทางเปิดติดกัน 3 รอบจึงเชื่อ
        # ▸ TURN จบเมื่อ odom บอกว่าเหลือหมุนไม่ถึง 3 องศา (จากนั้น ALIGN จะแก้ที่เหลือด้วย LiDAR)
        p('turn_tolerance_deg', 3.0)  # TURN ถือว่าเสร็จเมื่อเหลือน้อยกว่า 3 องศา (ตาม odom)

        # ▸ ◆ เปิดการใช้ LiDAR หากลางทางแยก (False = กลับไปใช้ odom นับครึ่งช่องแบบ v4)
        p('use_lidar_center', True)   # ◆ ใช้ LiDAR หาตำแหน่งกลางทางแยก
        # ▸ ◆ LiDAR อยู่หน้าจุดหมุนของหุ่นยนต์กี่เมตร (อยู่หลัง = ค่าลบ) ใช้ให้ "ตัวหุ่นยนต์" อยู่กลางทางแยก ไม่ใช่แค่ LiDAR
        p('lidar_offset_x', 0.0)      # ◆ ระยะ LiDAR หน้าจุดหมุน [m] (หน้า = บวก, หลัง = ลบ)
        # ▸ ◆ หยุดเมื่อคลาดจากกลางทางแยกไม่เกิน 1.5 cm
        p('center_tolerance', 0.015)  # ◆ ยอมให้คลาดจากกลางทางแยกได้ [m]
        # ▸ ◆ ความเร็วตอนเข้าใกล้ = ค่านี้ x ระยะที่เหลือ (เหลือ 10 cm -> 0.06 m/s)
        p('approach_kp', 0.6)         # ◆ ความแรงในการชะลอเข้าหาเป้า [(m/s)/m]
        # ▸ ◆ ความเร็วต่ำสุดตอนเข้าใกล้ (ช้ากว่านี้มอเตอร์อาจไม่หมุน)
        p('approach_speed', 0.03)     # ◆ ความเร็วต่ำสุดตอนเข้าใกล้เป้า [m/s]
        # ▸ ◆ ADVANCE ทำได้นานสุด 6 วินาที กันหุ่นยนต์เดินหน้า-ถอยหลังวนไม่จบ
        p('advance_timeout', 6.0)     # ◆ เวลาสูงสุดของ ADVANCE [s]
        # ▸ ◆ ข้อมูล LiDAR + คำสั่งผ่าน Wi-Fi ช้ากว่าความจริงราว 0.2 วินาที ระหว่างนั้นหุ่นยนต์ยังวิ่งต่อ
        #   จึงหักระยะ "ความเร็ว x 0.2 วินาที" ออกก่อนตัดสินใจหยุด (ถ้ายังเลย ลองเพิ่มเป็น 0.3)
        p('sensor_delay', 0.2)        # ◆ ความหน่วงของ LiDAR/คำสั่ง [s]

        # ▸ หลังจัดตัวตรงที่ทางแยก รอให้หุ่นยนต์หยุดสั่น 0.3 วินาที ก่อนเริ่มดูทาง
        p('settle_time', 0.3)         # จัดตัวตรงแล้ว รอนิ่งอีก 0.3 วินาที ก่อนโหวตทางแยก
        # ▸ ดูทาง 10 รอบ (0.5 วินาที) แล้วโหวต กันค่า LiDAR กระตุกครั้งเดียว
        p('decide_samples', 10)       # โหวตทางแยก 10 รอบ (0.5 วินาที)
        # ▸ ถามเราเมื่อทางแยกมีตั้งแต่ 3 ทาง (สามแยก/สี่แยก)
        p('ask_min_ways', 3)          # ถามเราเมื่อทางแยก >= 3 ทาง (2 = ถามทางโค้งด้วย, 5 = ไม่ถาม)

        # ▸ ★ เปิดการใช้ LiDAR วัดมุมกำแพง ถ้าปิด (False) จะใช้มุมจาก odom อย่างเดียว (เดินเบี้ยวง่าย)
        p('use_lidar_angle', True)    # ★ ใช้ LiDAR วัดมุมกำแพง (หัวใจของการวิ่งตรง)
        # ▸ ★ แถวที่แน่นที่สุดต้องมีจุดอย่างน้อย 10 จุด ถึงเชื่อว่าเห็นกำแพงจริง
        p('wall_min_pts', 10)         # ★ กำแพงที่ดีที่สุดต้องมีจุด LiDAR เรียงแถวอย่างน้อย 10 จุด
        # ▸ ★ "แถว" กว้าง 1 cm: จุดที่อยู่ห่างกันไม่เกิน 1 cm ในแนวตั้งฉากกำแพงจะนับเป็นแถวเดียวกัน
        p('wall_bin', 0.01)           # ★ ความกว้างของ "แถว" ที่ใช้นับจุด [m] (1 cm)
        # ▸ ★ ลองหมุนจุดตั้งแต่ -30 ถึง +30 องศา (หุ่นยนต์เอียงเกินนี้ไม่ได้ในทางเดินแคบ)
        p('wall_search_deg', 30.0)    # ★ ลองมุมตั้งแต่ -30 ถึง +30 องศา
        # ▸ ★ ใช้เฉพาะจุดที่อยู่ไม่เกิน 1.5 ช่องรอบตัว (30 cm -> 45 cm) = กำแพงใกล้ ๆ ที่วัดได้แม่น
        p('wall_range_cells', 1.5)    # ★ ใช้จุดที่อยู่ไม่เกิน 1.5 ช่องรอบตัว
        # ▸ ★ ไม่ใช้จุดที่ใกล้กว่า 8 cm เพราะอาจเป็นเสาอากาศหรือชิ้นส่วนของตัวหุ่นยนต์เอง
        p('ignore_below', 0.08)       # ★ ไม่ใช้จุดที่ใกล้กว่า 8 cm (อาจเป็นเสาอากาศ/ตัวหุ่นยนต์เอง)
        # ▸ ★ ขณะเดิน ขยับค่าทิศตาราง (grid_off) เข้าหาค่าที่ LiDAR วัดได้ทีละ 5% ต่อรอบ
        p('grid_corr_gain', 0.05)     # ★ ขณะเดิน ใช้มุมกำแพงแก้ทิศตารางทีละ 5% ต่อรอบ
        # ▸ ★ ALIGN ถือว่าตรงแล้วเมื่อเอียงจากกำแพงไม่เกิน 1.5 องศา
        p('align_tolerance_deg', 1.5) # ★ ALIGN เสร็จเมื่อเอียงจากกำแพงไม่เกิน 1.5 องศา
        # ▸ ★ ความแรงหมุนจัดตัว: เอียง 0.1 rad (5.7°) -> หมุน 0.2 rad/s
        p('align_kp', 2.0)            # ★ ความแรงในการหมุนจัดตัว (rad/s ต่อ rad ที่เอียง)
        # ▸ ★ หมุนจัดตัวช้าสุด 0.12 rad/s ถ้าสั่งช้ากว่านี้มอเตอร์อาจไม่หมุนเลย
        p('align_min_w', 0.12)        # ★ หมุนจัดตัวอย่างน้อย 0.12 rad/s (ช้ากว่านี้มอเตอร์อาจไม่ขยับ)
        # ▸ ★ จัดตัวนานสุด 3 วินาที ถ้ายังไม่ตรงก็ไปต่อ กันหุ่นยนต์ค้างอยู่ที่เดิม
        p('align_timeout', 3.0)       # ★ จัดตัวนานสุด 3 วินาที แล้วไปต่อ (กันค้าง)

        # ▸ เปิดระบบหลบกำแพง (safe_cmd) เมื่อหุ่นยนต์วิ่งเฉียงเข้าหากำแพง
        p('use_safety', True)         # เปิดระบบหลบกำแพงเมื่อเข้าใกล้เกินไป
        # ▸ ครึ่งความกว้างตัวหุ่นยนต์ (ตัวกว้าง 16 cm -> 0.08 m) วัดจากจุดกลาง LiDAR
        p('robot_half_width', 0.08)   # ครึ่งความกว้างตัวหุ่นยนต์ วัดจากจุดกลาง LiDAR [m] (ตัวกว้าง ~16 cm)
        # ▸ ระยะจากจุดกลาง LiDAR ถึงหน้าสุดของตัวหุ่นยนต์ (ใช้ตัดสินว่าชิดจนต้องหยุดเดินหน้า)
        p('robot_front', 0.10)        # ระยะจากจุดกลาง LiDAR ถึงหน้าสุดของตัวหุ่นยนต์ [m]
        # ▸ เผื่อด้านข้างอีก 2 cm: กล่องหลบกำแพงกว้างข้างละ 0.08 + 0.02 = 0.10 m
        p('safe_margin', 0.02)        # ระยะเผื่อด้านข้างตัว [m]
        # ▸ แรงหมุนหนี: กำแพงล้ำเข้ากล่อง 1 cm -> หมุนเพิ่ม 0.06 rad/s (บวกพื้นฐาน 0.2)
        p('k_avoid', 6.0)             # แรงหมุนหนี (rad/s ต่อเมตรที่กำแพงล้ำเข้ามาในกล่อง)
        # ▸ ระหว่างหลบกำแพง ลดความเร็วเดินหน้าเหลือ 0.03 m/s
        p('safe_speed', 0.03)         # ความเร็วเดินหน้าขณะหลบ [m/s]

        # ▸ บี๊บตอนหุ่นยนต์หยุดถามที่ทางแยก (ปิดไว้ก่อน เพราะต้องเช็ก topic กับ test_beep.py)

    #  ★★★ LiDAR: วัดมุมระหว่างหุ่นยนต์กับกำแพง (ทำให้วิ่งตรงขนานกำแพง) ★★★
    # ==========================================================================
    # ▸ ★ wall_score(x, y, th): ให้คะแนนว่าถ้าหมุนจุด LiDAR ไปมุม th แล้ว จุดเรียงเป็นแถวดีแค่ไหน
    #   ถ้า th ถูกต้อง จุดบนกำแพงเดียวกันจะมีพิกัดตั้งฉากเท่ากัน -> ตกลงแถวเดียว -> คะแนนสูง
    def wall_score(self, x, y, th):              # ★ ให้คะแนนว่าที่มุม th จุด LiDAR เรียงเป็นแถว (กำแพง) ดีแค่ไหน
        # ▸ ★ คำนวณ cos และ sin ของมุมทดลองไว้ใช้หมุนจุด
        c, s = math.cos(th), math.sin(th)        # ★ cos, sin ของมุมทดลอง
        # ▸ ★ หมุนจุด: u = พิกัดตามแนวที่เอียง th (กำแพงหน้า/หลังจะมี u เท่ากันทั้งแผ่น)
        u = x * c + y * s                        # ★ หมุนจุด: พิกัดตามแกนที่เอียง th (แถวของกำแพงหน้า/หลัง)
        # ▸ ★ หมุนจุด: v = พิกัดตั้งฉาก (กำแพงซ้าย/ขวาจะมี v เท่ากันทั้งแผ่น)
        v = -x * s + y * c                       # ★ หมุนจุด: พิกัดตามแกนตั้งฉาก (แถวของกำแพงซ้าย/ขวา)
        # ▸ ★ แบ่ง u เป็นช่องละ 1 cm แล้วนับว่าแต่ละช่องมีกี่จุด (bincount = นับจำนวนต่อช่อง)
        hu = np.bincount(np.floor((u - u.min()) / self.wall_bin).astype(int))   # ★ นับจุดในแต่ละแถว (กว้าง 1 cm) ตามแกน u
        # ▸ ★ ทำแบบเดียวกันกับ v
        hv = np.bincount(np.floor((v - v.min()) / self.wall_bin).astype(int))   # ★ นับจุดในแต่ละแถว ตามแกน v
        # ▸ ★ คะแนน = ผลรวมของ (จำนวนจุดในช่อง)² : จุด 20 จุดในช่องเดียว = 400 แต่กระจาย 4 ช่อง ช่องละ 5 = 100
        score = float(np.sum(hu.astype(float) ** 2) + np.sum(hv.astype(float) ** 2))   # ★ ผลรวมกำลังสอง: จุดรวมกันในแถวเดียวยิ่งได้คะแนนมาก
        # ▸ ★ คืนคะแนน และจำนวนจุดในช่องที่แน่นที่สุด (ใช้ดูว่าเห็นกำแพงชัดไหม)
        return score, int(max(hu.max(), hv.max()))   # ★ คืน (คะแนน, จำนวนจุดในแถวที่แน่นที่สุด)

    # ▸ ★ lidar_heading_error(): หามุมที่ต้องหมุนแก้ให้ขนานกำแพง โดยลองทุกมุมแล้วเลือกมุมที่คะแนนสูงสุด
    #   OUTPUT: มุม [rad] (+ = หมุนซ้าย, - = หมุนขวา) หรือ None ถ้าไม่เห็นกำแพงชัด
    def lidar_heading_error(self):               # ★ หาว่าหุ่นยนต์เอียงจากกำแพงกี่องศา (ใช้จุด LiDAR ทุกด้านพร้อมกัน)
        # ▸ ★ เลือกจุดที่ใช้ได้ และไม่ใกล้กว่า 8 cm (ตัดเสาอากาศ/ตัวเองทิ้ง)
        sel = (self.scan_ok & (self.scan_r >= self.ignore_below)            # ★ เลือกจุดที่ใช้ได้ ไม่ใกล้เกิน 8 cm
               # ▸ ★ และไม่ไกลเกิน 1.5 ช่อง (กำแพงไกลวัดมุมได้ไม่แม่นเท่ากำแพงใกล้)
               & (self.scan_r <= self.wall_range_cells * self.cell))       # ★ ... และไม่ไกลเกิน 1.5 ช่อง
        # ▸ ★ แปลงมุมของจุดที่เลือกจากองศาเป็นเรเดียน
        a = np.radians(self.scan_a[sel])         # ★ มุมของจุด (เรเดียน)
        # ▸ ★ แปลงจุด (ระยะ, มุม) เป็นพิกัด x = ระยะ x cos(มุม) (ไปข้างหน้า)
        x = self.scan_r[sel] * np.cos(a)         # ★ จุด -> พิกัด x (ไปข้างหน้า) [m]
        # ▸ ★ พิกัด y = ระยะ x sin(มุม) (ไปทางซ้าย)
        y = self.scan_r[sel] * np.sin(a)         # ★ จุด -> พิกัด y (ไปทางซ้าย) [m]
        # ▸ ★ ถ้าจุดน้อยกว่า 10 จุด ไม่พอจะหามุม
        if len(x) < self.wall_min_pts:           # ★ จุดน้อยเกินไป
            # ▸ ★ จำว่าไม่เห็นกำแพง
            self.wall_peak = 0                   # ★ ... ไม่มีกำแพงให้วัด
            # ▸ ★ คืน None = วัดมุมไม่ได้รอบนี้
            return None                          # ★ ... วัดไม่ได้
        # ▸ ★ เริ่มต้น: มุมที่ดีที่สุด = 0 คะแนน = -1 (ทุกมุมจะดีกว่านี้)
        best, best_score = 0.0, -1.0             # ★ มุมที่ดีที่สุดที่เจอ และคะแนน
        # ▸ ★ รอบหยาบ: ลองมุม -30, -29, ..., +30 องศา (ทีละ 1 องศา = 61 มุม)
        for th in np.arange(-self.wall_search, self.wall_search + 1e-9, math.radians(1.0)):   # ★ รอบหยาบ: ลองทุก 1 องศา
            # ▸ ★ คะแนนของมุมนี้ ([0] = เอาเฉพาะคะแนน)
            sc = self.wall_score(x, y, th)[0]    # ★ ... คะแนนของมุมนี้
            # ▸ ★ ถ้าคะแนนสูงกว่าที่เคยเจอ
            if sc > best_score:                  # ★ ... ดีกว่าที่เคยเจอ
                # ▸ ★ จำมุมนี้และคะแนนไว้
                best, best_score = th, sc        # ★ ...... จำไว้
        # ▸ ★ เก็บมุมที่ดีที่สุดของรอบหยาบไว้เป็นจุดกลางของรอบละเอียด
        coarse = best                            # ★ มุมที่ดีที่สุดจากรอบหยาบ
        # ▸ ★ รอบละเอียด: ลองรอบ ๆ มุมนั้น ±1 องศา ทีละ 0.1 องศา (21 มุม) ให้แม่นขึ้น
        for th in np.arange(coarse - math.radians(1.0), coarse + math.radians(1.0) + 1e-9, math.radians(0.1)):   # ★ รอบละเอียด: ทุก 0.1 องศา รอบ ๆ มุมนั้น
            # ▸ ★ คะแนนของมุมนี้
            sc = self.wall_score(x, y, th)[0]    # ★ ... คะแนน
            # ▸ ★ ถ้าดีกว่า
            if sc > best_score:                  # ★ ... ดีกว่า
                # ▸ ★ จำไว้
                best, best_score = th, sc        # ★ ...... จำไว้
        # ▸ ★ ที่มุมที่ดีที่สุด แถวที่แน่นที่สุดมีกี่จุด ([1] = จำนวนจุด)
        self.wall_peak = self.wall_score(x, y, best)[1]   # ★ จำนวนจุดบนกำแพงที่เรียงแถวดีที่สุด
        # ▸ ★ ถ้าแถวที่แน่นที่สุดยังมีจุดไม่ถึง 10 = ไม่มีกำแพงตรงให้เห็นชัด
        if self.wall_peak < self.wall_min_pts:   # ★ ไม่มีกำแพงไหนเรียงแถวชัดพอ
            # ▸ ★ ไม่เชื่อผลนี้ คืน None
            return None                          # ★ ... ไม่เชื่อผลนี้
        # ▸ ★ คืนมุมที่ดีที่สุด = มุมที่ต้องหมุนแก้ (เช่น +0.05 rad = ต้องหมุนซ้าย 2.9°)
        return float(best)                       # ★ มุมที่กำแพงเรียงตรงที่สุด = หุ่นยนต์เอียงเท่านี้ (+ หมุนซ้าย, - หมุนขวา)

    # ▸ grid_heading(): ทิศของตารางเขาวงกต (ใน odom) ที่ใกล้ทิศหุ่นยนต์ที่สุด
    #   เขาวงกตมีทิศแค่ 4 ทิศ (ห่างกัน 90°) จึงปัดทิศหุ่นยนต์ไปทิศที่ใกล้ที่สุด
    def grid_heading(self):                      # ทิศของตารางเขาวงกต (ใน odom) ที่ใกล้ทิศหุ่นยนต์ที่สุด
        # ▸ 90 องศาเป็นเรเดียน
        q = math.pi / 2                          # 90 องศา
        # ▸ หัก grid_off ออก ปัดเป็นทวีคูณ 90° แล้วบวก grid_off กลับ เช่น yaw 83°, grid_off 0 -> 90°
        return norm_angle(round(norm_angle(self.yaw - self.grid_off) / q) * q + self.grid_off)   # ปัดเป็นทวีคูณ 90 องศา (หัก/บวก grid_off)

    # ▸ ★ update_grid(gain): ใช้มุมที่ LiDAR วัดได้ แก้ค่า grid_off ให้ตรงกับเขาวงกตจริง
    #   ทำให้ grid_heading() ถูกต้องแม้ odom จะเพี้ยนไปเรื่อย ๆ
    def update_grid(self, gain=None):            # ★ ใช้มุมกำแพงแก้ทิศตาราง (grid_off) ให้ตรงกับเขาวงกตจริง
        # ▸ ★ ถ้าปิดการใช้ LiDAR หรือรอบนี้ไม่เห็นกำแพงชัด
        if not self.use_lidar_angle or self.wall_ang is None:   # ★ ไม่เห็นกำแพงตรง
            # ▸ ★ ไม่แก้อะไร
            return                               # ★ ... ไม่แก้
        # ▸ ★ ขณะเดินแก้ทีละ 5% (ค่อย ๆ แก้ กันกระตุก) แต่ตอนจัดตัวเสร็จจะส่ง gain=1.0 มาแก้เต็ม 100%
        k = self.grid_corr_gain if gain is None else gain   # ★ แก้ทีละ 5% (ขณะเดิน) หรือ 100% (ตอนจัดตัวเสร็จ)
        # ▸ ★ 90 องศาเป็นเรเดียน
        q = math.pi / 2                          # ★ 90 องศา
        # ▸ ★ ทิศของกำแพงในระบบ odom = ทิศหุ่นยนต์ + มุมที่ต้องหมุนแก้
        g = self.yaw + self.wall_ang             # ★ ทิศของกำแพงใน odom = ทิศตารางจริง
        # ▸ ★ ทิศกำแพงเบี่ยงจากทวีคูณ 90° เท่าไร = odom เพี้ยนไปเท่านั้น
        off = norm_angle(g - round(g / q) * q)   # ★ เบี่ยงจากทวีคูณ 90 องศาเท่าไร
        # ▸ ★ ขยับ grid_off เข้าหาค่าที่วัดได้ (5% หรือ 100%)
        self.grid_off = norm_angle(self.grid_off + k * norm_angle(off - self.grid_off))   # ★ ขยับ grid_off เข้าหาค่าจริง

    # ▸ ★ align_w(): คำนวณความเร็วหมุนอยู่กับที่ เพื่อจัดตัวให้ขนานกำแพง (ใช้ใน ALIGN และ DECIDE)
    #   OUTPUT: None = ไม่เห็นกำแพง, 0.0 = ตรงแล้ว, ค่าอื่น = ความเร็วหมุน [rad/s]
    def align_w(self):                           # ★ คำนวณความเร็วหมุนเพื่อจัดตัวให้ขนานกำแพง
        # ▸ ★ ถ้า LiDAR ไม่เห็นกำแพงชัด
        if self.wall_ang is None:                # ★ ไม่เห็นกำแพงตรงเลย
            # ▸ ★ จัดตัวไม่ได้ คืน None
            return None                          # ★ ... จัดตัวไม่ได้
        # ▸ ★ ถ้าเอียงน้อยกว่า 1.5 องศาแล้ว
        if abs(self.wall_ang) < self.align_tol:  # ★ เอียงไม่เกิน 1.5 องศาแล้ว
            # ▸ ★ ถือว่าตรงแล้ว คืน 0.0
            return 0.0                           # ★ ... ตรงแล้ว
        # ▸ ★ ความเร็วหมุน = 2 x มุมที่เอียง จำกัดไม่เกิน 0.3 rad/s (60% ของ turn_speed)
        w = clamp(self.align_kp * self.wall_ang, -0.6 * self.w_turn, 0.6 * self.w_turn)   # ★ หมุนแก้ตามมุมที่เอียง
        # ▸ ★ ถ้าช้ากว่า 0.12 rad/s มอเตอร์อาจไม่หมุนเลย
        if abs(w) < self.align_min_w:            # ★ ช้าเกินไป มอเตอร์อาจไม่หมุน
            # ▸ ★ ใช้ความเร็ว 0.12 rad/s ในทิศเดิม (copysign = เอาขนาดตัวแรก เครื่องหมายตัวที่สอง)
            w = math.copysign(self.align_min_w, w)   # ★ ... ใช้ความเร็วขั้นต่ำ
        # ▸ ★ คืนความเร็วหมุน
        return w                                 # ★ คืนความเร็วหมุน [rad/s]

    # ==========================================================================
    #  ◆◆◆ v5: LiDAR หา "กลางทางแยก" (หยุดตรงกลางพอดี ไม่วิ่งเลย) ◆◆◆
    # ==========================================================================
    # ▸ ◆ side_gap_center(xs): รับพิกัด x (ตามแนวทางเดิน) ของจุดบนแนวกำแพงข้างตัวด้านหนึ่ง
    #   แล้วหา "ช่องว่างของกำแพง" = ปากทางแยกด้านนั้น คืนตำแหน่ง x ของกลางปากทาง [m]
    #   ตัวอย่าง (ทาง 30 cm): กำแพงซ้ายจบที่ x = +0.05 แล้วมีกำแพงต่อที่ x = +0.33
    #   -> ปากทางกว้าง 0.28 m -> กลางปากทางอยู่ที่ x = +0.19 (ต้องเดินอีก 19 cm)
    def side_gap_center(self, xs):               # ◆ หากลางปากทางแยกจากจุดบนแนวกำแพงข้างตัว
        # ▸ ◆ ถ้าแทบไม่มีจุดบนแนวกำแพงด้านนี้ (เช่น อยู่กลางที่โล่ง) หาไม่ได้
        if xs.size < 3:                          # ◆ จุดน้อยเกินไป
            # ▸ ◆ คืน None = ไม่รู้
            return None                          # ◆ ... ไม่รู้
        # ▸ ◆ เรียงจุดจากหลังไปหน้า (x น้อยไปมาก)
        xs = np.sort(xs)                         # ◆ เรียงจากหลังไปหน้า
        # ▸ ◆ ช่องว่างที่ถือว่าเป็นปากทาง ต้องกว้างอย่างน้อย 0.6 ช่อง (ช่องเล็ก ๆ ระหว่างแผ่นกำแพงไม่นับ)
        min_gap = 0.6 * self.cell                # ◆ ปากทางต้องกว้างอย่างน้อย 0.6 ช่อง
        # ▸ ◆ ระยะห่างระหว่างจุดที่ติดกัน (np.diff) เช่น [0.01, 0.01, 0.28, 0.01, ...]
        d = np.diff(xs)                          # ◆ ระยะห่างระหว่างจุดที่ติดกัน
        # ▸ ◆ วนดูช่องว่างทุกช่อง จากหลังไปหน้า
        for i in np.nonzero(d >= min_gap)[0]:    # ◆ ทุกช่องว่างที่กว้างพอ
            # ▸ ◆ ขอบหลัง (a) และขอบหน้า (b) ของปากทาง
            a, b = xs[i], xs[i + 1]              # ◆ ขอบหลัง / ขอบหน้า ของปากทาง
            # ▸ ◆ เอาเฉพาะปากทางที่ขอบหน้ายังอยู่ข้างหน้าตัว (ปากทางที่ผ่านพ้นไปแล้วไม่สน)
            if b > 0.0:                          # ◆ ปากทางนี้ยังไม่ผ่านไปทั้งหมด
                # ▸ ◆ ถ้าความกว้างใกล้ 1 ช่อง ใช้ "กึ่งกลางระหว่างสองขอบ" (แม่นที่สุด ไม่ขึ้นกับความหนากำแพง)
                if b - a <= 1.4 * self.cell:     # ◆ เห็นทั้งสองขอบ และกว้างประมาณ 1 ช่อง
                    # ▸ ◆ กลางปากทาง = ค่าเฉลี่ยของสองขอบ
                    return 0.5 * (a + b)         # ◆ ... กลาง = (ขอบหลัง + ขอบหน้า) / 2
                # ▸ ◆ กว้างกว่านั้น (ข้างหน้าโล่งต่อ) ใช้ขอบหลัง + ครึ่งช่อง
                return a + 0.5 * self.cell       # ◆ ... กลาง = ขอบหลัง + ครึ่งช่อง
        # ▸ ◆ ไม่มีช่องว่างตรงกลาง: ดูว่ากำแพงด้านนี้ "จบ" ข้างหน้าก่อนสุดระยะที่มองหรือไม่
        if xs[-1] < 1.5 * self.cell - min_gap and xs[-1] > -0.5 * self.cell:   # ◆ กำแพงจบข้างหน้า แล้วโล่งต่อ
            # ▸ ◆ กลางปากทาง = ปลายกำแพง + ครึ่งช่อง
            return xs[-1] + 0.5 * self.cell      # ◆ ... กลาง = ปลายกำแพง + ครึ่งช่อง
        # ▸ ◆ กำแพงด้านนี้ต่อเนื่อง ไม่มีปากทาง
        return None                              # ◆ ไม่มีทางแยกด้านนี้

    # ▸ ◆ junction_remaining(): ต้องเดินอีกกี่เมตร "ตัวหุ่นยนต์" (จุดหมุน) จึงอยู่กลางทางแยกพอดี
    #   OUTPUT: บวก = ยังไม่ถึง, ลบ = เลยมาแล้ว (ต้องถอย), None = LiDAR ไม่เห็นปากทางแยก
    def junction_remaining(self):                # ◆ เหลืออีกกี่เมตรถึงกลางทางแยก (วัดจากกำแพงจริง)
        # ▸ ◆ มุมเอียงจากกำแพง (ถ้าไม่รู้ ถือว่า 0) ใช้หมุนจุดให้แกน x ขนานทางเดินพอดี
        th = self.wall_ang if self.wall_ang is not None else 0.0   # ◆ มุมเอียง (★ จาก LiDAR)
        # ▸ ◆ มุมของทุกลำแสงเป็นเรเดียน
        a = np.radians(self.scan_a)              # ◆ มุมทุกลำแสง
        # ▸ ◆ จุด -> พิกัด x (หน้า) เทียบ LiDAR
        x = self.scan_r * np.cos(a)              # ◆ x [m]
        # ▸ ◆ จุด -> พิกัด y (ซ้าย) เทียบ LiDAR
        y = self.scan_r * np.sin(a)              # ◆ y [m]
        # ▸ ◆ หมุนจุดด้วยมุมเอียง: u = ตามแนวทางเดิน (เหมือน wall_score)
        u = x * math.cos(th) + y * math.sin(th)  # ◆ พิกัดตามแนวทางเดิน
        # ▸ ◆ v = ตั้งฉากทางเดิน (+ ซ้าย, - ขวา)
        v = -x * math.sin(th) + y * math.cos(th) # ◆ พิกัดตั้งฉากทางเดิน
        # ▸ ◆ จุดที่ใช้ได้ ไม่ใกล้เกิน 8 cm และอยู่ช่วงหลัง 1 ช่อง ถึงหน้า 1.5 ช่อง
        ok = (self.scan_ok & (self.scan_r >= self.ignore_below)   # ◆ จุดที่ใช้ได้
              # ▸ ◆ ช่วงตามแนวทางเดิน: หลังตัว 1 ช่อง ถึงหน้าตัว 1.5 ช่อง
              & (u > -1.0 * self.cell) & (u < 1.5 * self.cell))  # ◆ ... ช่วงที่ดู
        # ▸ ◆ "แนวกำแพงข้างตัว" = แถบห่างจากกลางทาง 0.3 ถึง 0.75 ช่อง (กำแพงทางเดินอยู่ที่ 0.5 ช่อง)
        lo, hi = 0.3 * self.cell, self.wall_near # ◆ ขอบในและขอบนอกของแถบ
        # ▸ ◆ เก็บผลของแต่ละด้าน
        found = []                               # ◆ กลางปากทางที่เจอ
        # ▸ ◆ ทำทั้งด้านซ้าย (+1) และขวา (-1)
        for side in (1.0, -1.0):                 # ◆ ซ้าย แล้วขวา
            # ▸ ◆ จุดที่อยู่ในแถบกำแพงด้านนี้
            band = ok & (side * v >= lo) & (side * v <= hi)   # ◆ จุดบนแนวกำแพงด้านนี้
            # ▸ ◆ หากลางปากทางจากจุดเหล่านั้น
            c = self.side_gap_center(u[band])    # ◆ กลางปากทางด้านนี้
            # ▸ ◆ ถ้าเจอ
            if c is not None:                    # ◆ เจอปากทาง
                # ▸ ◆ เก็บไว้
                found.append(c)                  # ◆ ... เก็บ
        # ▸ ◆ ไม่เจอทั้งสองด้าน
        if not found:                            # ◆ ไม่เจอ
            # ▸ ◆ คืน None
            return None                          # ◆ ... ไม่รู้
        # ▸ ◆ ใช้ปากทางที่ใกล้ที่สุด (สามแยก/สี่แยก สองด้านควรได้ค่าเกือบเท่ากัน)
        c = min(found)                           # ◆ ปากทางที่ใกล้ที่สุด
        # ▸ ◆ แปลงจากจุด LiDAR เป็นจุดหมุนของตัวหุ่นยนต์ (LiDAR อยู่หน้าจุดหมุน -> ต้องเดินเพิ่มเท่านั้น)
        return c + self.lidar_offset_x           # ◆ ระยะที่ตัวหุ่นยนต์ต้องเดิน [m]

    # ▸ ◆ side_clear(side): ข้างตัวด้านนี้ "เปิดจริง" หรือไม่ (ใช้ตอนโหวตใน DECIDE)  side: +1 ซ้าย, -1 ขวา
    #   เปิดจริง = บนแนวกำแพงข้างตัว ช่วงหน้า-หลังตัว +/- 0.25 ช่อง ไม่มีจุดกำแพงเลย
    #   กันกรณี "หุ่นยนต์เลยทางแยกไปจนถึงกำแพง แล้ว LiDAR แอบเห็นปากทางแยกด้านหลัง"
    #   ซึ่งเดิมทำให้นับว่าข้างตัวเปิด แล้วถามเราทั้งที่ตรงนั้นเป็นแค่ทางเดิน/ทางโค้ง
    def side_clear(self, side):                  # ◆ ข้างตัวด้านนี้เปิดจริงหรือไม่
        # ▸ ◆ มุมเอียงจากกำแพง (ไม่รู้ = 0)
        th = self.wall_ang if self.wall_ang is not None else 0.0   # ◆ มุมเอียง
        # ▸ ◆ มุมทุกลำแสงเป็นเรเดียน
        a = np.radians(self.scan_a)              # ◆ มุมทุกลำแสง
        # ▸ ◆ จุด -> x (หน้า)
        x = self.scan_r * np.cos(a)              # ◆ x [m]
        # ▸ ◆ จุด -> y (ซ้าย)
        y = self.scan_r * np.sin(a)              # ◆ y [m]
        # ▸ ◆ พิกัดตามแนวทางเดิน (หมุนแก้มุมเอียงแล้ว)
        u = x * math.cos(th) + y * math.sin(th)  # ◆ ตามแนวทางเดิน
        # ▸ ◆ พิกัดตั้งฉากทางเดิน
        v = -x * math.sin(th) + y * math.cos(th) # ◆ ตั้งฉากทางเดิน
        # ▸ ◆ จุดกำแพงที่อยู่ "ข้างตัว" ด้านนี้: ห่างกลางทาง 0.3-0.75 ช่อง และหน้า-หลังไม่เกิน 0.25 ช่อง (ทาง 30 cm = 7.5 cm)
        wall = (self.scan_ok & (self.scan_r >= self.ignore_below)            # ◆ จุดที่ใช้ได้
                # ▸ ◆ อยู่ในแถบกำแพงด้านนี้
                & (side * v >= 0.3 * self.cell) & (side * v <= self.wall_near)   # ◆ ... แถบกำแพงข้างตัว
                # ▸ ◆ และอยู่ข้างตัวพอดี (เทียบจุดหมุน: หัก lidar_offset_x)
                & (np.abs(u + self.lidar_offset_x) <= 0.25 * self.cell))        # ◆ ... ตรงข้างตัว
        # ▸ ◆ มีจุดกำแพงไม่ถึง 3 จุด = ข้างตัวโล่งจริง
        return int(np.count_nonzero(wall)) < 3   # ◆ True = เปิดจริง

    # ▸ safe_cmd(v, w, m): ชั้นความปลอดภัย ตรวจว่ามีกำแพงล้ำเข้ามาใน "ทางที่ตัวหุ่นยนต์จะวิ่งผ่าน" ไหม
    #   INPUT: คำสั่ง (v, w) จากตัวควบคุมปกติ  OUTPUT: คำสั่งเดิม หรือคำสั่งหลบกำแพง
    def safe_cmd(self, v, w, m):                 # ชั้นความปลอดภัย: หมุนหนีเมื่อกำลังวิ่งเฉียงเข้าหากำแพง
        # ▸ ถ้าปิดระบบนี้ (-p use_safety:=false)
        if not self.use_safety:                  # ปิดระบบนี้อยู่
            # ▸ ส่งคำสั่งเดิมกลับไปโดยไม่แก้
            return v, w                          # ... ส่งคำสั่งเดิม
        # ▸ มุมของทุกลำแสงเป็นเรเดียน
        a = np.radians(self.scan_a)              # มุมทุกลำแสง (เรเดียน)
        # ▸ แปลงทุกจุดเป็นพิกัด x (ไปข้างหน้า)
        x = self.scan_r * np.cos(a)              # จุด -> x (ไปข้างหน้า) [m]
        # ▸ แปลงทุกจุดเป็นพิกัด y (ไปทางซ้าย)
        y = self.scan_r * np.sin(a)              # จุด -> y (ไปทางซ้าย) [m]
        # ▸ ครึ่งความกว้างของกล่อง = ครึ่งตัว + เผื่อ = 0.08 + 0.02 = 0.10 m
        box_w = self.half_w + self.safe_margin   # ครึ่งความกว้างของ "ทางที่ตัวจะวิ่งผ่าน" (ตัว + 2 cm)
        # ▸ ความยาวกล่องด้านหน้า = ระยะหยุดหน้ากำแพง - 1 cm (0.16 m) กำแพงตรงหน้าปกติจึงไม่อยู่ในกล่อง
        box_x = self.front_stop - 0.01           # ความยาวกล่องด้านหน้า (สั้นกว่าระยะหยุดหน้ากำแพง)
        # ▸ จุดที่อยู่ในกล่อง: ใช้ได้ ไม่ใกล้เกิน 8 cm และอยู่ด้านหน้า (x > 0)
        hit = (self.scan_ok & (self.scan_r >= self.ignore_below) & (x > 0.0)   # จุดที่ใช้ได้ อยู่ด้านหน้า
               # ▸ และ x ไม่เกินความยาวกล่อง และ |y| ไม่เกินครึ่งความกว้างกล่อง
               & (x <= box_x) & (np.abs(y) <= box_w))                          # ... และอยู่ในกล่องหน้าตัว
        # ▸ ถ้าไม่มีจุดไหนอยู่ในกล่องเลย = ทางวิ่งโล่ง (กำแพงขนานข้างตัวอยู่นอกกล่อง)
        if not hit.any():                        # ไม่มีกำแพงล้ำเข้ามาในทางวิ่ง
            # ▸ จำว่าไม่ได้หลบ
            self.avoiding = False                # ... ไม่ได้หลบ
            # ▸ ส่งคำสั่งเดิมกลับไป
            return v, w                          # ... ส่งคำสั่งเดิม
        # ▸ กำแพงล้ำเข้ามาลึกเท่าไร = ครึ่งกล่อง - |y| ของจุดที่ใกล้แนวกลางที่สุด
        depth = float(box_w - np.min(np.abs(y[hit])))   # กำแพงล้ำเข้ามาในกล่องลึกกี่เมตร
        # ▸ ถ้าเพิ่งเริ่มหลบ (รอบก่อนยังไม่ได้หลบ)
        if not self.avoiding:                    # เพิ่งเริ่มหลบ
            # ▸ พิมพ์เตือนใน Terminal ครั้งเดียว เช่น "Wall in the path (1.5 cm) -> steering away"
            self.get_logger().info(f'Wall in the path ({depth * 100:.1f} cm) -> steering away')   # ... บอกครั้งเดียว
        # ▸ จำว่ากำลังหลบ
        self.avoiding = True                     # กำลังหลบ
        # ▸ ค่าเฉลี่ย y ของจุดในกล่อง > 0 แปลว่ากำแพงอยู่ทางซ้าย -> หมุนขวา (-1) ไม่งั้นหมุนซ้าย (+1)
        away = -1.0 if float(np.mean(y[hit])) > 0 else 1.0   # กำแพงอยู่ทางซ้าย -> หมุนขวา, ทางขวา -> หมุนซ้าย
        # ▸ แรงหมุนหนี = 0.2 + 6 x ความลึก (ล้ำ 2 cm -> 0.32 rad/s) จำกัดไม่เกิน 0.5 rad/s
        w2 = clamp(away * (0.2 + self.k_avoid * depth), -self.w_turn, self.w_turn)   # แรงหมุนหนี (ยิ่งล้ำลึกยิ่งแรง)
        # ▸ ถ้ากำแพงชิดหน้าตัว (น้อยกว่า 11 cm) หยุดเดินหน้า หมุนอย่างเดียว ไม่งั้นเดินช้า 0.03 m/s
        v2 = 0.0 if float(np.min(x[hit])) < self.robot_front + 0.01 else min(v, self.safe_speed)   # ชิดหน้าตัวมาก -> หยุดเดินหน้า
        # ▸ ส่งคำสั่งหลบกำแพงกลับไป
        return v2, w2                            # คำสั่งใหม่

    # ==========================================================================
    #  การเคลื่อนที่
    # ==========================================================================
    # ▸ publish(v, w): ส่งคำสั่งความเร็วไปที่ /cmd_vel (เหมือน send_cmd_vel ใน test_cmd_vel.py)
    def publish(self, v, w):                 # ส่งคำสั่งความเร็ว (เหมือน test_cmd_vel.py)
        # ▸ สร้างข้อความ Twist เปล่า (ทุกค่าเป็น 0)
        msg = Twist()                        # ข้อความเปล่า
        # ▸ ใส่ความเร็วเดินหน้า (+ เดินหน้า, - ถอยหลัง)
        msg.linear.x = float(v)              # ความเร็วเดินหน้า [m/s]
        # ▸ ใส่ความเร็วหมุน (+ หมุนซ้าย, - หมุนขวา)
        msg.angular.z = float(w)             # ความเร็วหมุน [rad/s]
        # ▸ ส่งข้อความไปที่ /cmd_vel หุ่นยนต์จะขยับตามทันที
        self.pub.publish(msg)                # ส่งไป /cmd_vel
        # ▸ จำคำสั่งนี้ไว้ (ใช้ประมาณตำแหน่งถ้า /odom หาย)
        self.last_cmd = (v, w)               # จำไว้

    # ▸ stop_robot(): หยุดหุ่นยนต์อย่างปลอดภัย (เรียกตอนกด Ctrl+C)
    def stop_robot(self):                    # หยุดหุ่นยนต์อย่างปลอดภัย
        # ▸ ส่ง 5 ครั้ง เผื่อข้อความหายระหว่างทาง (Wi-Fi UDP)
        for _ in range(5):                   # ส่ง 5 ครั้ง กันข้อความหาย
            # ▸ ความเร็วเดินหน้า 0 และหมุน 0
            self.publish(0.0, 0.0)           # ความเร็ว 0
            # ▸ รอ 0.05 วินาทีก่อนส่งครั้งต่อไป
            time.sleep(0.05)                 # รอ 0.05 วินาที

    # ▸ traveled(): ระยะที่เดินไปแล้ว นับจากตอนเรียก start_segment() (ใช้ odom)
    def traveled(self):                      # ระยะที่เดินไปแล้วนับจาก start_segment()
        # ▸ ระยะเส้นตรง = sqrt(dx² + dy²) (ทฤษฎีพีทาโกรัส)
        return math.hypot(self.x - self.seg_x, self.y - self.seg_y)   # ระยะเส้นตรง (พีทาโกรัส)

    # ▸ start_segment(): จำตำแหน่งปัจจุบันเป็นจุดเริ่มวัดระยะ
    def start_segment(self):                 # จำตำแหน่งปัจจุบันเป็นจุดเริ่มวัดระยะ
        # ▸ เก็บ x, y ปัจจุบันไว้
        self.seg_x, self.seg_y = self.x, self.y   # เก็บ x, y

    # ▸ heading_hold(): คำนวณความเร็วหมุนเพื่อเดินตรง ใช้ตอนไม่มีกำแพงข้างตัว (เช่น กลางทางแยก)
    def heading_hold(self):                  # เดินตรง (ใช้ตอนไม่มีกำแพงข้างตัว เช่น กลางทางแยก)
        # ▸ ★ ถ้า LiDAR ยังเห็นกำแพงชัดด้านใดด้านหนึ่ง (หน้า หลัง หรือไกลออกไป)
        if self.use_lidar_angle and self.wall_ang is not None:   # ★ LiDAR ยังเห็นกำแพงด้านอื่น (หน้า/หลัง/ไกลออกไป)
            # ▸ ★ อัปเดตทิศสำรองให้ตรงกับตาราง (เผื่อรอบหน้า LiDAR ไม่เห็นกำแพง)
            self.heading_ref = self.grid_heading()               # ★ ... ให้ทิศสำรองตรงกับตาราง
            # ▸ ★ หมุนแก้ = 1.5 x มุมที่ LiDAR วัดได้ จำกัดไม่เกิน ±0.4 rad/s
            return clamp(self.kh * self.wall_ang, -self.max_corr, self.max_corr)   # ★ ... หมุนแก้ตามมุมกำแพงจริง
        # ▸ ไม่เห็นกำแพงเลย และยังไม่มีทิศเป้าหมาย
        if self.heading_ref is None:         # ไม่เห็นกำแพงเลย และยังไม่มีทิศเป้าหมาย
            # ▸ ใช้ทิศตารางที่ใกล้ที่สุดเป็นทิศเป้าหมาย
            self.heading_ref = self.grid_heading()   # ... ใช้ทิศตารางที่ใกล้ที่สุด
        # ▸ หมุนแก้ = 1.5 x (ทิศเป้าหมาย - ทิศปัจจุบันจาก odom) จำกัดไม่เกิน ±0.4 rad/s
        return clamp(self.kh * norm_angle(self.heading_ref - self.yaw), -self.max_corr, self.max_corr)   # ใช้ทิศจาก odom แทน

    # ▸ wall_follow_w(m): ตัวควบคุมเดินตามทางเดิน คืนความเร็วหมุน w
    #   w = แรงดึงเข้ากลางทาง (จำกัด ±0.10) + ★ 1.5 x มุมที่ต้องหมุนแก้ให้ขนานกำแพง
    def wall_follow_w(self, m):              # ตัวควบคุมเดินตามทางเดิน: w = ระยะ + ★ มุม
        # ▸ ★ มีกำแพงซ้ายของทางเดินไหม: ใกล้กว่า 0.75 ช่อง (30 cm -> 22.5 cm)
        lw = m['left_wall'] < self.wall_near      # ★ มีกำแพงซ้ายของทางเดิน (ใกล้กว่า 0.75 ช่อง)
        # ▸ ★ มีกำแพงขวาของทางเดินไหม (ขอบทางแยกที่อยู่ไกลกว่านี้ไม่นับ กันการดึงผิด)
        rw = m['right_wall'] < self.wall_near     # ★ มีกำแพงขวาของทางเดิน (ขอบทางแยกที่ไกลกว่านี้ไม่นับ)
        # ▸ ถ้ายังไม่มีทิศเป้าหมาย
        if self.heading_ref is None:              # ยังไม่มีทิศเป้าหมาย
            # ▸ ใช้ทิศตารางที่ใกล้ที่สุด
            self.heading_ref = self.grid_heading()   # ... ใช้ทิศตาราง
        # ▸ มุมคลาดเคลื่อนจาก odom (ใช้สำรองเผื่อ LiDAR ไม่เห็นกำแพงชัด)
        heading_err = norm_angle(self.heading_ref - self.yaw)   # มุมคลาดเคลื่อนจาก odom (ใช้สำรอง)
        # ▸ ★ ถ้า LiDAR เห็นกำแพงชัด
        if self.use_lidar_angle and self.wall_ang is not None:  # ★ LiDAR เห็นกำแพงตรง
            # ▸ ★ ใช้มุมที่วัดจากกำแพงจริงแทน (แม่นกว่า odom และไม่เพี้ยนตามเวลา)
            heading_err = self.wall_ang                         # ★ ใช้มุมที่วัดจากกำแพงจริงแทน (ไม่เพี้ยนตาม odom)
            # ▸ ★ อัปเดตทิศสำรองให้ตรงกับตารางที่แก้แล้ว
            self.heading_ref = self.grid_heading()              # ★ ให้ทิศสำรองตรงกับตารางที่แก้แล้ว
        # ▸ กรณีมีกำแพงทั้งสองข้าง
        if lw and rw:                             # กำแพงสองข้าง
            # ▸ ดึงเข้ากลางทาง: ใกล้กำแพงขวา (ซ้ายไกลกว่า) -> ค่าบวก -> หมุนไปทางซ้าย
            push = self.kp * (m['left_wall'] - m['right_wall'])     # แรงดึงเข้ากลางทาง (ใกล้ขวา -> บวก -> ไปซ้าย)
        # ▸ กรณีมีกำแพงขวาข้างเดียว
        elif rw:                                  # กำแพงขวาข้างเดียว
            # ▸ ห่างกำแพงขวาเกินครึ่งช่อง -> ค่าลบ -> หมุนเข้าหากำแพงขวา
            push = -self.kp * (m['right_wall'] - self.side_target)  # แรงดึงให้ห่างกำแพงขวาครึ่งช่อง
        # ▸ กรณีมีกำแพงซ้ายข้างเดียว
        elif lw:                                  # กำแพงซ้ายข้างเดียว
            # ▸ ห่างกำแพงซ้ายเกินครึ่งช่อง -> ค่าบวก -> หมุนเข้าหากำแพงซ้าย
            push = self.kp * (m['left_wall'] - self.side_target)    # แรงดึงให้ห่างกำแพงซ้ายครึ่งช่อง
        # ▸ กรณีไม่มีกำแพงข้างตัวเลย
        else:                                     # ไม่มีกำแพงข้างตัว
            # ▸ ใช้ heading_hold() เดินตรงแทน
            return self.heading_hold()            # ... เดินตรงตามทิศ odom
        # ▸ ★ จำกัดแรงดึงไม่เกิน ±0.10 rad/s: หุ่นยนต์จะเอียงเข้ากลางทางไม่เกิน ~4° (0.10 / 1.5 rad)
        push = clamp(push, -self.max_push, self.max_push)   # ★ จำกัดแรงดึงไม่เกิน 0.10 rad/s (เอียงเข้ากลางทางได้ไม่เกิน ~4 องศา)
        # ▸ ★ รวมสองแรง: ดึงเข้ากลางทาง + 1.5 x มุมที่ต้องหมุนแก้ให้ขนานกำแพง
        w = push + self.kh * heading_err          # ★ รวม: ดึงเข้ากลางทาง + คุมให้ขนานกำแพง
        # ▸ จำกัดผลรวมไม่เกิน ±0.4 rad/s
        return clamp(w, -self.max_corr, self.max_corr)   # จำกัดไม่เกิน +/- 0.4 rad/s

    # ▸ set_state(s): เปลี่ยนสถานะ และล้างตัวแปรที่ต้องเริ่มใหม่
    def set_state(self, s):                  # เปลี่ยนสถานะ
        # ▸ ตั้งสถานะใหม่
        self.state = s                       # สถานะใหม่
        # ▸ เริ่มนับรอบในสถานะใหม่จาก 0
        self.state_ticks = 0                 # เริ่มนับรอบใหม่
        # ▸ ◆ ล้างระยะถึงกลางทางแยก (สถานะใหม่จะวัดใหม่เอง)
        self.junc_rem = None                 # ◆ ล้างค่าที่แสดง
        # ▸ ◆ เริ่มนับรอบที่วิ่งช้าใหม่
        self.slow_ticks = 0                  # ◆ ล้างตัวนับ
        # ▸ ถ้าสถานะใหม่คือ DECIDE ต้องล้างค่าของการตัดสินใจครั้งก่อน
        if s == DECIDE:                      # เข้า DECIDE
            # ▸ ล้างคะแนนโหวตเป็น 0 ทุกทิศ
            self.open_votes = {'R': 0, 'F': 0, 'L': 0}   # ... ล้างคะแนนโหวต
            # ▸ ล้างจำนวนรอบโหวต
            self.vote_count = 0                          # ... ล้างจำนวนรอบโหวต
            # ▸ ★ ต้องจัดตัวตรงด้วย LiDAR ใหม่ก่อนดูทาง
            self.decide_aligned = False                  # ★ ... ต้องจัดตัวตรงก่อน

    # ▸ beep(): ส่งเสียงบี๊บให้รู้ว่าหุ่นยนต์รอคำตอบ (ทำงานเฉพาะเมื่อเปิด beep_on_ask)
    def beep(self):                          # บี๊บ (ถ้าเปิดใช้)
        # ▸ มี publisher เสียงบี๊บ (สร้างไว้ตอนเริ่มเมื่อ beep_on_ask = True)
        if self.beep_pub is not None:        # มี publisher เสียง
            # ▸ สร้างข้อความ UInt16
            msg = UInt16()                   # ข้อความ
            # ▸ ใส่ค่าความยาวเสียง
            msg.data = self.beep_ms          # ความยาวเสียง
            # ▸ ส่งไปที่ /beep
            self.beep_pub.publish(msg)       # ส่ง

    # ▸ start_turn(direction): เตรียมหมุน 'L' = ซ้าย 90°, 'R' = ขวา 90°, 'B' = กลับหลัง (ขวา 90° สองครั้ง)
    def start_turn(self, direction):         # เตรียมหมุน: 'L' = +90, 'R' = -90, 'B' = 180 องศา
        # ▸ มุมรวมที่ต้องหมุน (จำไว้แสดงผล): ซ้าย +90°, ขวา -90°, กลับหลัง -180°
        self.turn_goal = {'L': math.pi / 2, 'R': -math.pi / 2, 'B': -math.pi}[direction]   # มุมรวมที่ต้องหมุน
        # ▸ ★ หมุนครั้งละ 90°: ซ้าย +90°, นอกนั้น (ขวา/กลับหลัง) -90°
        self.turn_step = math.pi / 2 if direction == 'L' else -math.pi / 2   # ★ หมุนครั้งละ 90 องศา
        # ▸ ★ กลับหลังแบ่งเป็น 2 ครั้ง จัดตัวด้วย LiDAR ระหว่างกลาง ล้อลื่นแค่ไหนก็ไม่หลงทิศ
        self.turn_steps = 2 if direction == 'B' else 1   # ★ กลับหลัง = หมุนขวา 90 สองครั้ง (จัดตัวด้วย LiDAR ระหว่างกลาง)
        # ▸ ทิศเป้าหมายของครั้งนี้ = ทิศตารางปัจจุบัน + 90° (เริ่มจากทิศตาราง จึงไม่สะสมความเอียง)
        self.turn_target = norm_angle(self.grid_heading() + self.turn_step)   # ทิศเป้าหมายของครั้งนี้ = ทิศตาราง + 90
        # ▸ เปลี่ยนเป็นสถานะ TURN
        self.set_state(TURN)                 # เข้าสถานะ TURN

    # ▸ execute(direction, auto, options): ทำตามการตัดสินใจ (ของเราหรือของหุ่นยนต์) และจดบันทึกเส้นทาง
    def execute(self, direction, auto, options):   # ทำตามการตัดสินใจ และจดบันทึกเส้นทาง
        # ▸ นับการตัดสินใจเพิ่ม 1
        self.junction_no += 1                      # นับการตัดสินใจ
        # ▸ เวลาตั้งแต่เริ่มโปรแกรม (วินาที)
        t = time.time() - self.start_time          # เวลาตั้งแต่เริ่ม
        # ▸ จดบันทึกเส้นทาง 1 บรรทัด (f-string 3 ส่วนต่อกัน)
        self.route_log.append(                     # จดบันทึก 1 บรรทัด:
            # ▸ ส่วนที่ 1: ลำดับ (#03) เวลา และตำแหน่งจาก odom
            f'#{self.junction_no:02d}  t={t:6.1f}s  pos=({self.x:+.2f},{self.y:+.2f})  '   # ลำดับ เวลา ตำแหน่ง
            # ▸ ส่วนที่ 2: ทางที่เปิด (เช่น RF) และทางที่เลือก
            f'open={"".join(options) or "-"}  choice={DIR_NAME[direction]}  '              # ทางที่เปิด ทางที่เลือก
            # ▸ ส่วนที่ 3: หุ่นยนต์เลือกเอง (auto) หรือเราเลือก (user)
            f'{"(auto)" if auto else "(user)"}')                                            # ใครเลือก
        # ▸ พิมพ์บอกใน Terminal เช่น "-> RIGHT (your choice)"
        self.get_logger().info(f'-> {DIR_NAME[direction]} {"(auto)" if auto else "(your choice)"}')   # พิมพ์บอก
        # ▸ ถ้าเลือกตรงไป ไม่ต้องหมุน
        if direction == 'F':                       # ตรงไป
            # ▸ ทิศที่จะเดิน = ทิศตารางปัจจุบัน
            self.heading_ref = self.grid_heading() # ... ทิศที่จะเดิน
            # ▸ เริ่มวัดระยะจากตรงนี้
            self.start_segment()                   # ... เริ่มวัดระยะ
            # ▸ เข้าสถานะ EXIT เดินออกจากทางแยก
            self.set_state(EXIT)                   # ... เดินออกจากทางแยก
        # ▸ ถ้าเลือกซ้าย ขวา หรือกลับหลัง
        else:                                      # ซ้าย ขวา กลับหลัง
            # ▸ เริ่มหมุนก่อน
            self.start_turn(direction)             # ... หมุนก่อน

    # ▸ measure_cell(m): วัดความกว้างทางเดินตอนเริ่ม (เมื่อไม่ได้ตั้ง cell_size)
    def measure_cell(self, m):               # วัดความกว้างทางเดินตอนเริ่ม (เมื่อ cell_size = 0)
        # ▸ ถ้าเห็นกำแพงทั้งสองข้างในระยะ 0.6 m
        if m['left_wall'] < 0.6 and m['right_wall'] < 0.6:   # เห็นกำแพงทั้งสองข้าง
            # ▸ ความกว้างทางเดิน = ระยะกำแพงซ้าย + ระยะกำแพงขวา (เช่น 0.15 + 0.15 = 0.30)
            self.cell_samples.append(m['left_wall'] + m['right_wall'])   # ... ความกว้าง = ซ้าย + ขวา
        # ▸ ถ้าเก็บได้ครบ 10 ค่าแล้ว
        if len(self.cell_samples) >= 10:     # ได้ 10 ค่าแล้ว
            # ▸ ใช้ค่ากลาง (median) กันค่าผิดปกติบางค่า
            width = float(np.median(self.cell_samples))   # ... ใช้ค่ากลาง
            # ▸ พิมพ์ค่าที่วัดได้ใน Terminal
            self.get_logger().info(f'Measured corridor width {width:.3f} m')   # ... บอกค่าที่วัดได้
            # ▸ ตั้งขนาดช่อง (จำกัดให้อยู่ระหว่าง 0.25 ถึง 0.60 m กันค่าเพี้ยน)
            self.apply_cell(clamp(width, 0.25, 0.60))     # ... ตั้งขนาดช่อง
        # ▸ ถ้าผ่านไป 2 วินาที (40 รอบ) แล้วยังไม่เห็นกำแพงสองข้าง
        elif self.state_ticks > 2 * self.rate:   # 2 วินาทีแล้วยังไม่เห็นกำแพงสองข้าง
            # ▸ พิมพ์เตือนว่าจะใช้ค่าเริ่มต้น
            self.get_logger().info('Cannot see both walls -> using cell_size 0.30 m')   # ... เตือน
            # ▸ ใช้ 0.30 m
            self.apply_cell(0.30)            # ... ใช้ 0.30 m

    # ==========================================================================
    #  LOOP หลัก ทำงาน 20 ครั้งต่อวินาที (timer เรียกให้)
    # ==========================================================================
    # ▸ loop(): "สมอง" ของหุ่นยนต์ ทุก 0.05 วินาที อ่านข้อมูลล่าสุด เลือกทำตามสถานะ แล้วส่งคำสั่งความเร็ว
    def loop(self):                               # "สมอง" ของหุ่นยนต์
        # ▸ อ่านเวลาปัจจุบัน
        now = time.time()                         # เวลาปัจจุบัน
        # ▸ เวลาที่ผ่านไปตั้งแต่รอบก่อน (ประมาณ 0.05 วินาที)
        dt = now - self.last_loop_time            # เวลาที่ผ่านไปจากรอบก่อน (~0.05 s)
        # ▸ จำเวลารอบนี้ไว้ใช้รอบหน้า
        self.last_loop_time = now                 # จำไว้

        # ▸ ถ้าไม่ได้ /odom มานานเกิน 0.5 วินาที (odom หาย)
        if now - self.last_odom_time > 0.5:       # /odom หายไปเกิน 0.5 วินาที
            # ▸ ประมาณตำแหน่งเองจากคำสั่งล่าสุดที่ส่งไป (dead reckoning)
            v, w = self.last_cmd                  # ... ประมาณตำแหน่งจากคำสั่งที่ส่งไป
            # ▸ yaw ใหม่ = yaw เดิม + ความเร็วหมุน x เวลา
            self.yaw = norm_angle(self.yaw + w * dt)      # ... yaw ใหม่
            # ▸ x ใหม่ = x เดิม + v x cos(yaw) x เวลา
            self.x += v * math.cos(self.yaw) * dt         # ... x ใหม่
            # ▸ y ใหม่ = y เดิม + v x sin(yaw) x เวลา
            self.y += v * math.sin(self.yaw) * dt         # ... y ใหม่

        # ▸ ถ้ายังไม่เคยได้ข้อมูล LiDAR เลย
        if self.scan_r is None:                   # ยังไม่มีข้อมูล LiDAR
            # ▸ ยังทำอะไรไม่ได้ รอรอบหน้า
            return                                # ... รอ
        # ▸ วัดระยะทุกทิศจาก scan ล่าสุด (front, left, right, left_wall, right_wall)
        m = self.measure()                        # วัดระยะทุกทิศ
        # ▸ นับรอบในสถานะปัจจุบันเพิ่ม 1
        self.state_ticks += 1                     # นับรอบในสถานะนี้
        # ▸ ถ้ายังไม่รู้ความกว้างทางเดิน
        if self.cell is None:                     # ยังไม่รู้ขนาดช่อง
            # ▸ หยุดนิ่งระหว่างวัด
            self.publish(0.0, 0.0)                # ... หยุดนิ่ง
            # ▸ วัดความกว้างทางเดิน (ต้องได้ 10 ค่า)
            self.measure_cell(m)                  # ... วัดความกว้างทางเดิน
            # ▸ จบรอบนี้ รอบหน้าค่อยทำงานต่อ
            return                                # ... รอบหน้าค่อยทำงานต่อ
        # ▸ ★ วัดมุมที่ต้องหมุนแก้ให้ขนานกำแพงด้วย LiDAR ทุกรอบ (None ถ้าปิดใช้หรือไม่เห็นกำแพง)
        self.wall_ang = self.lidar_heading_error() if self.use_lidar_angle else None   # ★ วัดว่าหุ่นยนต์เอียงจากกำแพงกี่องศา
        # ▸ ★ ถ้ากำลังเดินในทางเดิน (FOLLOW หรือ EXIT)
        if self.state in (FOLLOW, EXIT):          # ★ กำลังเดินในทางเดิน
            # ▸ ★ ใช้มุมกำแพงแก้ทิศตารางทีละ 5% (แก้ odom ที่เพี้ยน)
            self.update_grid()                    # ★ ... ใช้มุมกำแพงแก้ทิศตารางทีละนิด
        # ▸ พิมพ์บรรทัดสถานะวินาทีละครั้ง
        self.print_status(m, now)                 # พิมพ์สถานะวินาทีละครั้ง

        # ---------------- FOLLOW: เดินตามทางเดิน ----------------
        # ▸ สถานะ FOLLOW: เดินตามทางเดิน คอยดูกำแพงหน้าและทางเปิดด้านข้าง
        if self.state == FOLLOW:                  # สถานะ FOLLOW
            # ▸ ถ้ากำแพงหน้าใกล้กว่าระยะหยุด (0.17 m) = ถึงกลางช่องสุดท้ายแล้ว
            #   ◆ หักระยะที่วิ่งไปแล้วระหว่างข้อมูลหน่วง (ความเร็วล่าสุด x 0.2 s) ออกก่อน
            if m['front'] - self.last_cmd[0] * self.sensor_delay < self.front_stop:   # กำแพงข้างหน้าใกล้ (ถึงกลางช่องสุดท้ายแล้ว)
                # ▸ หยุด
                self.publish(0.0, 0.0)            # ... หยุด
                # ▸ ไปสถานะ DECIDE เพื่อดูว่าไปทางไหนต่อ
                self.set_state(DECIDE)            # ... ไปตัดสินใจ
                # ▸ จบรอบนี้
                return                            # ... จบรอบนี้
            # ▸ ซ้ายเปิด (ไกลกว่า 1 ช่อง) -> นับเพิ่ม 1, ไม่เปิด -> เริ่มนับใหม่จาก 0
            self.left_cnt = self.left_cnt + 1 if m['left'] > self.open_dist else 0     # นับว่าซ้ายเปิดติดกันกี่รอบ
            # ▸ ขวาเปิด -> นับเพิ่ม 1, ไม่เปิด -> เริ่มนับใหม่จาก 0
            self.right_cnt = self.right_cnt + 1 if m['right'] > self.open_dist else 0  # นับว่าขวาเปิดติดกันกี่รอบ
            # ▸ ◆ LiDAR หาปากทางแยกข้างหน้า (เห็นได้ก่อนถึง) None = ไม่เห็น
            self.junc_rem = self.junction_remaining() if self.use_lidar_center else None   # ◆ เหลืออีกกี่เมตรถึงกลางทางแยก
            # ▸ ◆ ถ้าเห็นทางแยกที่อยู่ใกล้กว่า 0.75 ช่อง -> นับเพิ่ม 1, ไม่งั้นเริ่มนับใหม่
            self.ahead_cnt = (self.ahead_cnt + 1 if self.junc_rem is not None   # ◆ นับว่าเห็นปากทางข้างหน้าติดกันกี่รอบ
                              # ▸ ◆ เงื่อนไข: ใกล้กว่า 0.75 ช่อง (ทาง 30 cm -> 22.5 cm) จึงเริ่มชะลอ
                              and self.junc_rem < 0.75 * self.cell else 0)     # ◆ ... ต้องใกล้กว่า 0.75 ช่อง
            # ▸ ถ้าซ้ายหรือขวาเปิดติดกันครบ 3 รอบ = เจอทางแยกจริง  ◆ หรือ LiDAR เห็นปากทางข้างหน้าครบ 3 รอบ
            if (self.left_cnt >= self.confirm_n or self.right_cnt >= self.confirm_n   # เปิดครบ 3 รอบ = เจอทางแยก
                    # ▸ ◆ หรือเห็นปากทางแยกข้างหน้า (ก่อนถึง) ครบ 3 รอบ
                    or self.ahead_cnt >= self.confirm_n):                            # ◆ ... หรือเห็นปากทางล่วงหน้า
                # ▸ พิมพ์บอกใน Terminal
                self.get_logger().info('Side opening detected -> moving to junction centre')  # ... บอก
                # ▸ จำทิศตารางไว้เดินตรงเข้าทางแยก
                self.heading_ref = self.grid_heading()   # ... ทิศที่จะเดินต่อ
                # ▸ เริ่มวัดระยะจากตรงนี้ (ใช้เป็นค่าสำรองถ้า LiDAR หาปากทางไม่เจอ)
                self.start_segment()              # ... เริ่มวัดระยะ
                # ▸ ◆ ระยะสำรอง: ถ้า LiDAR บอกระยะได้ใช้ค่านั้น ไม่งั้นครึ่งช่องแบบ v4
                self.adv_dist = self.junc_rem if self.junc_rem is not None else self.center_offset   # ◆ ระยะสำรอง
                # ▸ ◆ ล้างตัวนับ
                self.ahead_cnt = 0                # ◆ ล้างตัวนับ
                # ▸ เข้าสถานะ ADVANCE
                self.set_state(ADVANCE)           # ... เดินเข้ากลางทางแยก
                # ▸ จบรอบนี้
                return                            # ... จบรอบนี้
            # ▸ ◆ ชะลอเมื่อใกล้กำแพงหน้า: ความเร็ว = 0.6 x (ระยะที่เหลือก่อนจุดหยุด) แต่ไม่ต่ำกว่า 0.03 และไม่เกิน 0.08 m/s
            v = clamp(self.approach_kp * (m['front'] - self.front_stop), self.approach_speed, self.v)   # ◆ ใกล้กำแพงหน้าแล้วช้าลง
            # ▸ ◆ ถ้า LiDAR เห็นทางแยกข้างหน้าแล้ว เริ่มชะลอตั้งแต่ตอนนี้ (ไม่ต้องรอเข้า ADVANCE)
            if self.junc_rem is not None and self.junc_rem < self.cell:   # ◆ ทางแยกอยู่ใกล้กว่า 1 ช่อง
                # ▸ ◆ ความเร็ว = 0.6 x ระยะที่เหลือ (ไม่ต่ำกว่า 0.03 m/s)
                v = min(v, max(self.approach_speed, self.approach_kp * self.junc_rem))   # ◆ ... ชะลอก่อนถึง
            # ▸ เดินหน้า + ★ หมุนแก้ให้อยู่กลางทางและขนานกำแพง แล้วผ่าน safe_cmd ตรวจการชน ก่อนส่งไป /cmd_vel
            self.publish(*self.safe_cmd(v, self.wall_follow_w(m), m))   # เดินหน้า + ★ คุมให้ขนานกำแพง + หลบถ้าใกล้

        # ---------------- ADVANCE: เดินเข้ากลางทางแยก ----------------
        # ▸ ◆ สถานะ ADVANCE (v5): เดินเข้า (หรือถอยกลับ) จนตัวหุ่นยนต์อยู่กลางทางแยกพอดี โดยวัดจากกำแพงด้วย LiDAR
        elif self.state == ADVANCE:               # ◆ สถานะ ADVANCE
            # ▸ ถ้ากำแพงหน้าใกล้กว่าระยะหยุด = อยู่กลางช่องสุดท้ายแล้ว
            if m['front'] < self.front_stop:      # กำแพงหน้าใกล้
                # ▸ หยุด
                self.publish(0.0, 0.0)            # ... หยุด
                # ▸ ไปตัดสินใจ
                self.set_state(DECIDE)            # ... ไปตัดสินใจ
                # ▸ จบรอบนี้
                return                            # ... จบรอบนี้
            # ▸ ◆ ถาม LiDAR ว่าเหลืออีกกี่เมตรถึงกลางทางแยก
            rem = self.junction_remaining() if self.use_lidar_center else None   # ◆ ระยะที่เหลือ (จากกำแพงจริง)
            # ▸ ◆ ถ้า LiDAR ไม่เห็นปากทาง ใช้ค่าสำรองจาก odom: ระยะที่ต้องเดิน - ระยะที่เดินไปแล้ว
            if rem is None:                       # ◆ LiDAR หาไม่เจอ
                # ▸ ◆ ค่าสำรองจาก odom
                rem = self.adv_dist - self.traveled()   # ◆ ... ใช้ odom แทน
            # ▸ ◆ หักระยะที่หุ่นยนต์วิ่งไปแล้วระหว่างที่ข้อมูลยังหน่วงอยู่ (เช่น 0.03 m/s x 0.2 s = 6 mm)
            rem -= self.last_cmd[0] * self.sensor_delay   # ◆ ชดเชยความหน่วง
            # ▸ ◆ จำไว้พิมพ์ในบรรทัดสถานะ
            self.junc_rem = rem                   # ◆ จำไว้แสดงผล
            # ▸ ◆ นับรอบที่สั่งวิ่งช้าติดกัน (คำสั่งผ่าน Wi-Fi ก็หน่วง ต้องสั่งช้าสักพักหุ่นยนต์ถึงช้าลงจริง)
            self.slow_ticks = self.slow_ticks + 1 if abs(self.last_cmd[0]) <= self.approach_speed + 1e-3 else 0   # ◆ นับรอบที่วิ่งช้า
            # ▸ ◆ ต้องสั่งช้าติดกันนานกว่าความหน่วง (0.2 s = 4 รอบ) จึงเชื่อว่าหุ่นยนต์ช้าลงแล้วจริง
            slow_enough = self.slow_ticks > self.sensor_delay * self.rate   # ◆ หุ่นยนต์ช้าลงจริงแล้ว
            # ▸ ◆ ถึงกลางทางแยกแล้ว = คลาดไม่เกิน 1.5 cm "และ" หุ่นยนต์ช้าลงจริงแล้ว (ถ้ายังวิ่งเร็ว หยุดทันทีจะไถลเลย)
            #   หรือทำนานเกิน 6 วินาที (กันเดินหน้า-ถอยหลังวนไม่จบ)
            if ((abs(rem) <= self.center_tol and slow_enough)   # ◆ ตรงกลาง + ช้าแล้ว
                    # ▸ ◆ หรือหมดเวลา
                    or self.state_ticks > self.adv_ticks_max):   # ◆ ... หรือหมดเวลา
                # ▸ ◆ หยุด
                self.publish(0.0, 0.0)            # ◆ ... หยุด
                # ▸ ◆ พิมพ์ว่าหยุดห่างกลางทางแยกเท่าไร (ใช้ตรวจสอบ)
                self.get_logger().info(f'At junction centre (error {rem * 100:+.1f} cm)')   # ◆ ... บอกค่าคลาด
                # ▸ ◆ ไปตัดสินใจ (ถามเรา)
                self.set_state(DECIDE)            # ◆ ... ไปตัดสินใจ
                # ▸ ◆ จบรอบนี้
                return                            # ◆ ... จบรอบนี้
            # ▸ ◆ ความเร็ว = 0.6 x ระยะที่เหลือ (ใกล้แล้วช้าลงเอง) ไม่เกิน 0.08 m/s; ค่าลบ = ถอยหลัง (เลยมาแล้ว)
            v = clamp(self.approach_kp * rem, -self.v, self.v)   # ◆ ชะลอตามระยะที่เหลือ
            # ▸ ◆ ถ้าช้ากว่า 0.03 m/s มอเตอร์อาจไม่หมุน
            if abs(v) < self.approach_speed:      # ◆ ช้าเกินไป
                # ▸ ◆ ใช้ 0.03 m/s ในทิศเดิม (เดินหน้าหรือถอย)
                v = math.copysign(self.approach_speed, v)   # ◆ ... ใช้ความเร็วต่ำสุด
            # ▸ ◆ เดินหน้า: ผ่าน safe_cmd ตรวจการชนด้วย
            if v > 0:                             # ◆ เดินหน้า
                # ▸ ◆ เดินตรงตามทิศกำแพง (★ heading_hold) + ระบบหลบกำแพง
                self.publish(*self.safe_cmd(v, self.heading_hold(), m))   # ◆ ... เดินหน้าช้า ๆ
            # ▸ ◆ ถอยหลัง (เลยกลางทางแยกมาแล้ว)
            else:                                 # ◆ ถอยหลัง
                # ▸ ◆ ถอยตรง ๆ ช้า ๆ (★ heading_hold คุมมุม)
                self.publish(v, self.heading_hold())   # ◆ ... ถอยกลับเข้ากลางทางแยก

        # ---------------- DECIDE: จัดตัวตรง -> รอนิ่ง -> โหวต -> ตัดสินใจ ----------------
        # ▸ สถานะ DECIDE: ขั้น 1 จัดตัวตรง, ขั้น 2 รอนิ่ง, ขั้น 3 โหวตทางเปิด แล้วตัดสินใจ
        elif self.state == DECIDE:                # สถานะ DECIDE
            # ▸ ★ ขั้น 1: ถ้ายังไม่ได้จัดตัวให้ตรงกับกำแพง
            if not self.decide_aligned:           # ★ ขั้น 1: ยังไม่ได้จัดตัวตรง
                # ▸ ★ ถาม LiDAR ว่าต้องหมุนแก้เท่าไร (None / 0.0 / ความเร็วหมุน)
                w = self.align_w()                # ★ ... LiDAR บอกว่าต้องหมุนเท่าไร
                # ▸ ★ ถ้ายังเอียง (w ไม่ใช่ 0 และไม่ใช่ None) และยังไม่หมดเวลา 3 วินาที
                if w and self.state_ticks <= self.align_ticks_max:   # ★ ... ยังเอียง และยังไม่หมดเวลา
                    # ▸ ★ หมุนอยู่กับที่ (ไม่เดินหน้า) เพื่อจัดตัว
                    self.publish(0.0, w)          # ★ ...... หมุนอยู่กับที่จัดตัว
                    # ▸ ★ รอบหน้าวัดมุมใหม่
                    return                        # ★ ...... รอบหน้าวัดใหม่
                # ▸ ★ ตรงแล้ว (หรือหมดเวลา / ไม่เห็นกำแพง) -> หยุดหมุน
                self.publish(0.0, 0.0)            # ★ ... ตรงแล้ว (หรือหมดเวลา) -> หยุด
                # ▸ ★ ถ้าตรงกับกำแพงจริง (w == 0.0)
                if w == 0.0:                      # ★ ... ถ้าตรงจริง
                    # ▸ ★ ตั้งทิศตารางใหม่ให้ตรงกับทิศนี้เต็ม 100%
                    self.update_grid(gain=1.0)    # ★ ...... ตั้งทิศตารางใหม่ให้ตรงกับกำแพงเต็ม ๆ
                # ▸ ★ จำว่าขั้น 1 เสร็จแล้ว
                self.decide_aligned = True        # ★ ... จำว่าจัดตัวแล้ว
                # ▸ จำรอบที่เริ่มรอนิ่ง
                self.settle_start = self.state_ticks   # ... เริ่มนับเวลารอนิ่ง
                # ▸ จบรอบนี้
                return                            # ... จบรอบนี้
            # ▸ หยุดนิ่งตลอดขั้น 2 และ 3
            self.publish(0.0, 0.0)                # หยุดนิ่ง
            # ▸ ขั้น 2: ถ้ายังรอนิ่งไม่ครบ 6 รอบ (0.3 วินาที)
            if self.state_ticks - self.settle_start <= self.settle_ticks:   # ขั้น 2: รอนิ่ง 0.3 วินาที
                # ▸ รอต่อ
                return                            # ... ยังไม่ครบ
            # ▸ ขั้น 3: โหวตรอบนี้ (นับรอบเพิ่ม 1)
            self.vote_count += 1                  # ขั้น 3: โหวตรอบนี้
            # ▸ ถ้าขวาว่างไกลกว่า 1 ช่อง ◆ และไม่มีกำแพงอยู่ข้างตัวทางขวาจริง ๆ บวกคะแนนขวา 1 (True = 1, False = 0)
            self.open_votes['R'] += m['right'] > self.open_dist and self.side_clear(-1.0)   # ขวาเปิด +1 (◆ และข้างตัวโล่งจริง)
            # ▸ ถ้าหน้าว่างไกลกว่า 1 ช่อง บวกคะแนนหน้า 1
            self.open_votes['F'] += m['front'] > self.open_dist   # หน้าเปิด +1
            # ▸ ถ้าซ้ายว่างไกลกว่า 1 ช่อง ◆ และไม่มีกำแพงอยู่ข้างตัวทางซ้ายจริง ๆ บวกคะแนนซ้าย 1
            self.open_votes['L'] += m['left'] > self.open_dist and self.side_clear(1.0)     # ซ้ายเปิด +1 (◆ และข้างตัวโล่งจริง)
            # ▸ ถ้ายังโหวตไม่ครบ 10 รอบ
            if self.vote_count < self.decide_samples:             # ยังโหวตไม่ครบ 10 รอบ
                # ▸ รอโหวตรอบหน้า
                return                                            # ... รอบหน้า
            # ▸ ทิศที่เปิด = ทิศที่ได้คะแนนเกินครึ่ง เรียงขวา หน้า ซ้าย (ลำดับกฎมือขวา)
            options = [d for d in ('R', 'F', 'L')                 # ทิศที่เปิด (เรียงตามกฎมือขวา)
                       # ▸ คะแนน x 2 > จำนวนรอบ = เกินครึ่ง (เช่น 6 x 2 = 12 > 10)
                       if self.open_votes[d] * 2 > self.vote_count]   # ... ได้คะแนนเกินครึ่ง
            # ▸ จำนวนทาง = ทางที่เปิด + ทางที่เดินมา 1 ทาง
            ways = len(options) + 1               # จำนวนทาง = ทางเปิด + ทางที่มา
            # ▸ พิมพ์ผลใน Terminal เช่น "3-WAY JUNCTION (T-junction)  open=RF  votes R10 F10 L0 of 10"
            self.get_logger().info(               # บอกผล
                # ▸ ส่วนที่ 1: ชนิดทางแยก และทางที่เปิด
                f'{JUNCTION_NAME[ways]}  open={"".join(options) or "-"}  '        # ชนิดทางแยก ทางเปิด
                # ▸ ส่วนที่ 2: คะแนนขวาและหน้า
                f'votes R{self.open_votes["R"]} F{self.open_votes["F"]} '          # คะแนน
                # ▸ ส่วนที่ 3: คะแนนซ้าย และจำนวนรอบโหวต
                f'L{self.open_votes["L"]} of {self.vote_count}')                   # ... ต่อ
            # ▸ ถ้าเป็นสามแยกหรือสี่แยก (>= 3 ทาง) -> ต้องถามเรา
            if ways >= self.ask_min_ways and options:     # สามแยก / สี่แยก
                # ▸ จำทางที่เปิดไว้
                self.ask_options = options        # ... จำทางเปิด
                # ▸ จำชนิดทางแยก (3 หรือ 4)
                self.ask_ways = ways              # ... จำชนิด
                # ▸ ถ้ามีปุ่มที่เผลอกดค้างไว้ในคิว
                while not self.input_q.empty():   # ... ล้างปุ่มที่กดค้าง
                    # ▸ ดึงทิ้งให้หมด กันหุ่นยนต์ใช้คำตอบเก่า
                    self.input_q.get_nowait()     # ...... ดึงทิ้ง
                # ▸ บี๊บ (ถ้าเปิดใช้)
                self.beep()                       # ... บี๊บ
                # ▸ วาดรูปทางแยกและพิมพ์คำถาม
                self.prompt()                     # ... ถาม
                # ▸ เข้าสถานะ ASK รอคำตอบ
                self.set_state(ASK)               # ... รอคำตอบ
            # ▸ ถ้าไม่มีทางเปิดเลย = ทางตัน
            elif not options:                     # ทางตัน
                # ▸ กลับหลังเองโดยไม่ถาม (auto = True)
                self.execute('B', True, options)  # ... กลับหลังเอง
            # ▸ ถ้าเปิดทางเดียว = ทางโค้ง
            else:                                 # ทางโค้ง
                # ▸ ไปทางเดียวที่เปิดเองโดยไม่ถาม
                self.execute(options[0], True, options)   # ... ไปทางเดียวที่เปิด

        # ---------------- ASK: รอคำตอบ ----------------
        # ▸ สถานะ ASK: หยุดนิ่ง แล้วเช็กคิวคีย์บอร์ดทุกรอบโดยไม่รอ
        elif self.state == ASK:                   # สถานะ ASK
            # ▸ ส่งความเร็ว 0 ทุกรอบ กันหุ่นยนต์ไหล
            self.publish(0.0, 0.0)                # หยุดนิ่ง
            # ▸ ลองดึงคำตอบจากคิว
            try:                                  # ลองดึงคำตอบ
                # ▸ ดึงทันทีไม่รอ (get_nowait)
                ans = self.input_q.get_nowait()   # ... ไม่รอ
            # ▸ ถ้าคิวว่าง (เรายังไม่ได้พิมพ์)
            except queue.Empty:                   # ยังไม่มีคำตอบ
                # ▸ จบรอบนี้ รอบหน้าค่อยเช็กใหม่
                return                            # ... รอบหน้าเช็กใหม่
            # ▸ ถ้ากด Enter อย่างเดียว (ข้อความว่าง)
            if ans == '':                         # กด Enter เฉย ๆ
                # ▸ เลือกทางแรกในรายการ = ทางตามกฎมือขวา (ขวา > ตรง > ซ้าย)
                choice = self.ask_options[0]      # ... ตามกฎมือขวา
            # ▸ ถ้าพิมพ์อะไรมา
            else:                                 # พิมพ์มา
                # ▸ แปลงเป็นรหัสทิศ ถ้าพิมพ์ไม่รู้จักจะได้ None
                choice = INPUT_MAP.get(ans)       # ... แปลงเป็นรหัสทิศ
            # ▸ ถ้าพิมพ์ไม่ถูก
            if choice is None:                    # พิมพ์ไม่ถูก
                # ▸ บอกว่าไม่เข้าใจ
                print(f'  "{ans}" not understood.')   # ... บอก
                # ▸ ถามใหม่
                self.prompt()                     # ... ถามใหม่
                # ▸ จบรอบนี้
                return                            # ... จบรอบ
            # ▸ ถ้าเลือกทางที่ LiDAR เห็นว่ามีกำแพง (ยกเว้นกลับหลัง)
            if choice not in self.ask_options and choice != 'B':   # เลือกทางที่ LiDAR เห็นว่าตัน
                # ▸ เตือน แต่ยังทำตามที่เราสั่ง
                print(f'  {DIR_NAME[choice]} looks blocked by the LiDAR - going anyway.')   # ... เตือน
            # ▸ ทำตามที่เราเลือก (auto = False)
            self.execute(choice, False, self.ask_options)   # ทำตามที่เลือก

        # ---------------- TURN: หมุนตาม odom ----------------
        # ▸ สถานะ TURN: หมุนอยู่กับที่จนทิศ odom ถึงเป้าหมาย
        elif self.state == TURN:                  # สถานะ TURN
            # ▸ มุมที่ยังต้องหมุน = ทิศเป้าหมาย - ทิศปัจจุบัน (บีบให้อยู่ใน ±180°)
            remaining = norm_angle(self.turn_target - self.yaw)   # เหลือต้องหมุนอีกเท่าไร (ตาม odom)
            # ▸ ถ้าเหลือน้อยกว่า 3 องศา (ตาม odom)
            if abs(remaining) < self.turn_tol:    # เหลือน้อยกว่า 3 องศา
                # ▸ หยุดหมุน
                self.publish(0.0, 0.0)            # ... หยุดหมุน
                # ▸ ★ จัดตัวด้วย LiDAR เสร็จแล้วให้เดินออก (EXIT)
                self.align_next = EXIT            # ★ ... จัดตัวด้วย LiDAR เสร็จแล้วค่อยเดินออก
                # ▸ ★ ไป ALIGN: odom อาจบอกว่าครบแต่ล้อลื่น หุ่นยนต์จริงยังเอียงอยู่
                self.set_state(ALIGN)             # ★ ... ไปสถานะ ALIGN (odom อาจคลาดเพราะล้อลื่น)
                # ▸ จบรอบนี้
                return                            # ... จบรอบ
            # ▸ ความเร็วหมุน = 2 x มุมที่เหลือ (ใกล้ถึงจะช้าลง กันหมุนเกิน) จำกัดไม่เกิน ±0.5
            w = clamp(2.0 * remaining, -self.w_turn, self.w_turn)   # หมุน = 2 x มุมที่เหลือ (ใกล้ถึงช้าลง)
            # ▸ ถ้าช้ากว่า 0.2 rad/s
            if abs(w) < 0.2:                      # ช้าเกิน
                # ▸ ใช้ 0.2 rad/s ในทิศเดิม (ช้ากว่านี้มอเตอร์อาจไม่หมุน)
                w = math.copysign(0.2, w)         # ... อย่างน้อย 0.2 rad/s
            # ▸ ส่งคำสั่งหมุนอยู่กับที่ (เดินหน้า 0)
            self.publish(0.0, w)                  # หมุนอยู่กับที่

        # ---------------- ★ ALIGN: LiDAR จัดตัวให้ขนานกำแพง ----------------
        # ▸ ★ สถานะ ALIGN: หมุนแก้อยู่กับที่ตามมุมที่ LiDAR วัดได้ จนขนานกำแพง
        elif self.state == ALIGN:                 # ★ สถานะ ALIGN
            # ▸ ★ ถาม LiDAR ว่าต้องหมุนแก้เท่าไร
            w = self.align_w()                    # ★ LiDAR บอกว่าต้องหมุนแก้เท่าไร
            # ▸ ★ ถ้ายังเอียงเกิน 1.5° และยังไม่หมดเวลา 3 วินาที
            if w and self.state_ticks <= self.align_ticks_max:   # ★ ยังเอียงเกิน 1.5 องศา และยังไม่หมดเวลา
                # ▸ ★ หมุนแก้อยู่กับที่
                self.publish(0.0, w)              # ★ ... หมุนแก้อยู่กับที่
                # ▸ ★ รอบหน้าวัดมุมใหม่
                return                            # ★ ... รอบหน้าวัดใหม่
            # ▸ ★ ตรงแล้ว (หรือหมดเวลา / ไม่เห็นกำแพง) -> หยุด
            self.publish(0.0, 0.0)                # ★ ตรงแล้ว (หรือหมดเวลา / ไม่เห็นกำแพง) -> หยุด
            # ▸ ★ ถ้าตรงกับกำแพงจริง
            if w == 0.0:                          # ★ ตรงกับกำแพงจริง
                # ▸ ★ ตั้งทิศตารางให้ตรงกับทิศนี้เต็ม 100% (ล้างความเพี้ยนของ odom)
                self.update_grid(gain=1.0)        # ★ ... ตั้งทิศตารางให้ตรงกับทิศนี้เต็ม ๆ
            # ▸ ★ หมุนเสร็จไป 1 ครั้ง
            self.turn_steps -= 1                  # ★ หมุนเสร็จไป 1 ครั้ง
            # ▸ ★ ถ้ายังต้องหมุนอีก (กำลังกลับหลัง ครั้งแรกเพิ่งเสร็จ)
            if self.turn_steps > 0:               # ★ ยังต้องหมุนอีก (กำลังกลับหลัง)
                # ▸ ★ ทิศเป้าหมายครั้งถัดไป = ทิศตารางที่เพิ่งจัดตรง + 90°
                self.turn_target = norm_angle(self.grid_heading() + self.turn_step)   # ★ ... ทิศเป้าหมายครั้งถัดไป
                # ▸ ★ กลับไป TURN หมุนอีก 90°
                self.set_state(TURN)              # ★ ... หมุนอีก 90 องศา
                # ▸ ★ จบรอบนี้
                return                            # ★ ... จบรอบ
            # ▸ ทิศที่จะเดินต่อ = ทิศตารางปัจจุบัน
            self.heading_ref = self.grid_heading()   # ทิศที่จะเดินต่อ
            # ▸ เริ่มวัดระยะจากตรงนี้
            self.start_segment()                  # เริ่มวัดระยะ
            # ▸ ไปสถานะถัดไป: FOLLOW (ตอนเริ่มโปรแกรม) หรือ EXIT (หลังเลี้ยว)
            self.set_state(self.align_next)       # ไปสถานะถัดไป (FOLLOW ตอนเริ่ม, EXIT หลังเลี้ยว)

        # ---------------- EXIT: เดินออกจากทางแยก 1 ช่อง ----------------
        # ▸ สถานะ EXIT: เดินออกจากทางแยก 1 ช่อง ไม่สนใจทางเปิดด้านข้างระหว่างนี้
        elif self.state == EXIT:                  # สถานะ EXIT
            # ▸ ถ้ากำแพงหน้าใกล้กว่าระยะหยุด
            if m['front'] < self.front_stop:      # กำแพงหน้าใกล้
                # ▸ หยุด
                self.publish(0.0, 0.0)            # ... หยุด
                # ▸ ไปตัดสินใจใหม่
                self.set_state(DECIDE)            # ... ตัดสินใจใหม่
                # ▸ จบรอบนี้
                return                            # ... จบรอบ
            # ▸ ถ้าเดินออกมาครบ 1 ช่องแล้ว
            if self.traveled() >= self.exit_dist: # ออกมาครบ 1 ช่อง
                # ▸ ล้างตัวนับทางเปิด (เริ่มนับใหม่ใน FOLLOW)
                self.left_cnt = self.right_cnt = 0     # ... รีเซ็ตตัวนับ
                # ▸ ถ้าด้านข้างยังเปิด = ช่องนี้เป็นทางแยกอีก
                if m['left'] > self.open_dist or m['right'] > self.open_dist:   # ... ข้างยังเปิด = ทางแยกอีก
                    # ▸ ◆ เริ่มวัดระยะใหม่ (ค่าสำรอง)
                    self.start_segment()          # ◆ ...... เริ่มวัดระยะ
                    # ▸ ◆ ตาม odom ควรอยู่กลางทางแยกพอดีแล้ว (ระยะสำรอง = 0)
                    self.adv_dist = 0.0           # ◆ ...... ระยะสำรอง 0
                    # ▸ ◆ ไป ADVANCE ให้ LiDAR จัดตำแหน่งกลางทางแยกก่อนตัดสินใจ (เดิมไป DECIDE ทันที)
                    self.set_state(ADVANCE)       # ◆ ...... จัดตำแหน่งกลางทางแยก
                # ▸ ถ้าด้านข้างเป็นกำแพง = ทางเดินปกติ
                else:                             # ... ข้างเป็นกำแพง
                    # ▸ กลับไปเดินตามทาง
                    self.set_state(FOLLOW)        # ...... เดินตามทางต่อ
                # ▸ จบรอบนี้
                return                            # ... จบรอบ
            # ▸ ยังไม่ครบ: เดินหน้า + ★ คุมให้ขนานกำแพง + ผ่าน safe_cmd ตรวจการชน
            self.publish(*self.safe_cmd(self.v, self.wall_follow_w(m), m))   # เดินหน้า + ★ ขนานกำแพง + หลบถ้าใกล้


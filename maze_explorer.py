    # ▸ @staticmethod: ฟังก์ชันนี้ไม่ใช้ข้อมูลของโหนด (ไม่มี self)
    @staticmethod                                 # ไม่ใช้ข้อมูลของโหนด
    # ▸ junction_picture(opts): วาดรูปทางแยกเป็นตัวอักษร 5 บรรทัด ทิศที่ปิดเขียนว่า (wall)
    def junction_picture(opts):                   # วาดรูปทางแยก (ทิศที่ปิดเขียนว่า wall)
        # ▸ ด้านบน: ถ้าหน้าเปิดเขียน "[w] FORWARD" ไม่งั้นเขียน "(wall)"
        top = '[w] FORWARD' if 'F' in opts else '  (wall)   '    # ด้านหน้า
        # ▸ เส้นเชื่อมด้านบน: เปิด = "|", ปิด = "=" (กำแพง)
        stem = '|' if 'F' in opts else '='                       # เส้นด้านบน
        # ▸ ด้านซ้าย: เปิดเขียน "[a] LEFT ---" ไม่งั้นเขียน "(wall)"
        left = '[a] LEFT ---' if 'L' in opts else '    (wall) |'  # ด้านซ้าย
        # ▸ ด้านขวา: เปิดเขียน "--- [d] RIGHT" ไม่งั้นเขียน "(wall)"
        right = '--- [d] RIGHT' if 'R' in opts else '| (wall)'    # ด้านขวา
        # ▸ คืน list ของ 5 บรรทัด
        return [                                                 # 5 บรรทัด
            # ▸ บรรทัด 1: ทางด้านหน้า
            '              ' + top,                              # หน้า
            # ▸ บรรทัด 2: เส้นเชื่อมด้านบน
            '                   ' + stem,                        # เส้น
            # ▸ บรรทัด 3: ซ้าย - หุ่นยนต์ - ขวา
            '  ' + left + ' ROBOT ' + right,                     # ซ้าย-หุ่นยนต์-ขวา
            # ▸ บรรทัด 4: เส้นเชื่อมด้านล่าง
            '                   |',                              # เส้น
            # ▸ บรรทัด 5: ทางที่เดินมา
            '               (came from)',                        # ทางที่มา
        ]                                                        # ปิด list

    # ▸ prompt(): พิมพ์ชนิดทางแยก รูปทางแยก และคำถามใน Terminal
    def prompt(self):                             # พิมพ์คำถามที่ทางแยก
        # ▸ ขึ้นบรรทัดใหม่ แล้วพิมพ์เส้น ===== ยาว 60 ตัว
        print('\n' + '=' * 60)                    # เส้นคั่น
        # ▸ พิมพ์ชนิดทางแยก เช่น "3-WAY JUNCTION (T-junction)"
        print(f'  {JUNCTION_NAME.get(self.ask_ways, "JUNCTION")}   '   # ชนิดทางแยก
              # ▸ ต่อด้วยลำดับทางแยก และบอกว่าหุ่นยนต์หยุดแล้ว
              f'#{self.junction_no + 1}   - robot stopped')            # ลำดับ
        # ▸ พิมพ์เส้นคั่นอีกเส้น
        print('=' * 60)                           # เส้นคั่น
        # ▸ วนทุกบรรทัดของรูปทางแยก
        for line in self.junction_picture(self.ask_options):   # รูปทางแยก
            # ▸ พิมพ์ทีละบรรทัด
            print(line)                           # ... ทีละบรรทัด
        # ▸ เรียงตัวเลือก: ซ้าย ขวา หน้า (เฉพาะที่เปิด) แล้วต่อด้วยกลับหลังเสมอ
        order = [d for d in ('L', 'R', 'F') if d in self.ask_options] + ['B']   # ตัวเลือก
        # ▸ พิมพ์ตัวเลือก เช่น "Choose: [a] LEFT / [d] RIGHT / [s] BACK"
        print('  Choose: ' + ' / '.join(f'[{KEY_OF[d]}] {DIR_NAME[d]}' for d in order))   # พิมพ์ตัวเลือก
        # ▸ บอกว่ากด Enter เฉย ๆ = ทางตามกฎมือขวา
        print(f'  (just Enter = {DIR_NAME[self.ask_options[0]]}, right-hand rule)')    # Enter = กฎมือขวา
        # ▸ พิมพ์ "> " ไม่ขึ้นบรรทัดใหม่ เป็นที่ให้พิมพ์คำตอบ (flush = แสดงทันที)
        print('> ', end='', flush=True)           # ที่ให้พิมพ์คำตอบ

    # ▸ print_status(m, now): พิมพ์บรรทัดสถานะวินาทีละครั้ง ใช้ตรวจว่า LiDAR วัดถูกไหม
    def print_status(self, m, now):               # พิมพ์สถานะวินาทีละครั้ง
        # ▸ ถ้ายังไม่ครบ 1 วินาทีจากครั้งก่อน หรือกำลังรอคำตอบ (ไม่ให้ข้อความแทรกคำถาม)
        if now - self.last_status < 1.0 or self.state == ASK:   # ยังไม่ครบ 1 วินาที หรือกำลังถาม
            # ▸ ไม่พิมพ์
            return                                # ... ไม่พิมพ์
        # ▸ จำเวลาที่พิมพ์ครั้งนี้
        self.last_status = now                    # จำเวลา
        # ▸ ฟังก์ชันสั้น: แปลงระยะเป็นข้อความทศนิยม 2 ตำแหน่ง (หรือ inf ถ้าไกลมาก)
        f = lambda d: ' inf' if math.isinf(d) else f'{d:4.2f}'  # ระยะ -> ข้อความ
        # ▸ ★ มุมที่ต้องหมุนแก้เป็นองศา (มีเครื่องหมาย + / -) หรือ "--" ถ้าไม่เห็นกำแพง
        ang = '  -- ' if self.wall_ang is None else f'{math.degrees(self.wall_ang):+5.1f}'   # ★ มุมเอียงจากกำแพง (องศา)
        # ▸ ◆ ระยะที่เหลือถึงกลางทางแยกเป็น cm หรือ "--" ถ้าไม่เห็นปากทาง
        jr = ' --' if self.junc_rem is None else f'{self.junc_rem * 100:+.0f}cm'   # ◆ เหลืออีกกี่ cm ถึงกลางทางแยก
        # ▸ พิมพ์บรรทัดสถานะ เช่น "[FOLLOW ] F=0.45 L=0.15 R=0.16 ang= +0.8 pts=31"
        self.get_logger().info(                   # บรรทัดสถานะ เช่น [FOLLOW ] F=0.45 L=0.15 R=0.16 ang= +0.8 pts=31
            # ▸ ส่วนที่ 1: สถานะ และระยะหน้า ซ้าย ขวา
            f'[{self.state:7s}] F={f(m["front"])} L={f(m["left"])} R={f(m["right"])} '   # ... สถานะ + ระยะ
            # ▸ ส่วนที่ 2: ★ มุมที่ต้องหมุนแก้ และจำนวนจุดบนกำแพงหลัก
            f'ang={ang} pts={self.wall_peak} junc={jr}')    # ... ★ มุมเอียง + จำนวนจุด + ◆ ระยะถึงกลางทางแยก

